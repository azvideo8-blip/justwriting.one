-- D4.17: картотека упомянутых в заметках людей убрана из продукта.
--
-- Имена и характер отношений извлекались из заметок автоматически и ложились
-- в отдельный столбец сводки. Люди, о которых речь, согласия не давали и дать
-- его не могли, а пользователь не вправе дать его за них. Перестать писать
-- недостаточно — столбец нужно снести вместе с содержимым.
--
-- Порядок применения: сначала выкатывается клиент, который это поле больше не
-- отправляет, и только потом миграция. В обратном порядке старый клиент
-- получит от PostgREST ошибку "column not found" на каждой записи сводки.
--
-- На момент написания таблица пуста (0 строк), так что удаление ничего не
-- ломает и ничего не теряет, кроме самого столбца.

alter table public.ai_summaries drop column if exists mentioned_people;
