-- Согласие на обработку специальных категорий персональных данных (ст. 10
-- 152-ФЗ) — отдельное поле, а не признак внутри общего согласия.
--
-- Отдельность здесь не формальность: согласие с политикой и согласие на
-- спецкатегории даются и отзываются независимо, и доказывать их придётся по
-- отдельности. Одно поле на двоих не позволило бы показать, на что именно
-- человек согласился.
alter table public.users
  add column if not exists ai_consent_at      timestamptz,
  add column if not exists ai_consent_version integer;
