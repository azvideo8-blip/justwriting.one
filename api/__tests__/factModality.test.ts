import { describe, it, expect } from 'vitest';
import { isIrrealis, splitFactsByModality } from '../ai/pure';

/**
 * Два случая ниже — настоящие: пользователь написал в заметках, что собирается
 * купить подписку и что ему предложили аудит за 10 тысяч, а ИИ отвечал ему, что
 * подписка куплена и консультация получена. Это и есть баг, который здесь
 * закрывается, поэтому оба сформулированы дословно по тем заметкам.
 */

describe('isIrrealis', () => {
  it('распознаёт намерение по маркерам', () => {
    const intentions = [
      'завтра видимо куплю про подписку клод',
      'на этой неделе переезжает на новую платформу',
      'нужно заработать денег на аудит',
      'придётся ждать пока лимиты сбросятся',
      'планирует доделать сайт и потом заплатить юристу',
      'хочет купить подписку',
      'если появятся деньги, закажет аудит',
      'наверное возьмёт полный пакет за 40к',
      'думаю, что план такой будет',
      'собирается сделать email',
    ];
    for (const s of intentions) {
      expect(isIrrealis(s), s).toBe(true);
    }
  });

  it('не трогает состоявшиеся события', () => {
    const facts = [
      'купил домен и VPS',
      'начал переезд приложения на новую платформу',
      'получил предложение об аудите за 10 тысяч',
      'из одной фирмы перезвонили',
      'использовано около 80% недельных лимитов',
      'написал в пару фирм',
    ];
    for (const s of facts) {
      expect(isIrrealis(s), s).toBe(false);
    }
  });

  it('считает намерением решительно высказанное намерение', () => {
    // «Решимость — не факт»: пока нет сообщения о действии, действия не было.
    expect(isIrrealis('на этот месяц точно покупает подписку, решил купить')).toBe(true);
  });

  it('нормализует ё', () => {
    expect(isIrrealis('придется подождать')).toBe(true);
    expect(isIrrealis('придётся подождать')).toBe(true);
  });
});

describe('splitFactsByModality', () => {
  it('переносит намерение из фактов в планы', () => {
    const { facts, commitments } = splitFactsByModality(
      ['купил домен и VPS', 'завтра видимо куплю подписку клод'],
      [],
    );
    expect(facts).toEqual(['купил домен и VPS']);
    expect(commitments).toEqual(['завтра видимо куплю подписку клод']);
  });

  it('оставляет факт получения предложения фактом, а оплату — планом', () => {
    const { facts, commitments } = splitFactsByModality(
      ['получил предложение об аудите за 10 тысяч', 'нужно заработать и заказать аудит'],
      [],
    );
    expect(facts).toEqual(['получил предложение об аудите за 10 тысяч']);
    expect(commitments).toEqual(['нужно заработать и заказать аудит']);
  });

  it('дописывает в конец существующих планов и не дублирует', () => {
    const { facts, commitments } = splitFactsByModality(
      ['хочет купить подписку', 'сделал бэкап'],
      ['Хочет купить подписку', 'планирует переехать'],
    );
    expect(facts).toEqual(['сделал бэкап']);
    expect(commitments).toEqual(['Хочет купить подписку', 'планирует переехать']);
  });

  it('ничего не меняет, когда все факты состоявшиеся', () => {
    const input = ['купил домен', 'настроил nginx'];
    const { facts, commitments } = splitFactsByModality(input, ['планирует релиз']);
    expect(facts).toEqual(input);
    expect(commitments).toEqual(['планирует релиз']);
  });

  it('переносит все факты, если все они намерения', () => {
    const { facts, commitments } = splitFactsByModality(['буду переезжать', 'надо купить'], []);
    expect(facts).toEqual([]);
    expect(commitments).toEqual(['буду переезжать', 'надо купить']);
  });
});
