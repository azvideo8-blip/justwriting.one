import { describe, expect, it } from 'vitest';
import { sanitizeCitations } from '../useAIChat';
import { extractContextTitles } from '../../services/chatContext/citations';

// DLG-Q8 (Fable T-18): выдумка коуча выглядела так: [«Новая копилка»,
// 18.09.2026], [«Разговор», 28.09.2026]. Такие скобки проходили насквозь, потому
// что чистились только ссылки формата CITATION_RE. Проверяется и обратное:
// законное оформление (markdown-ссылка, чекбокс, сноска [1]) тронуто быть не
// должно.
const REAL = 'local_d5751490abcd';
const IDS = [REAL];

describe('Q-8 (а): нераспознанные квадратные скобки', () => {
  it('скобки-названия с датой удаляются вместе с пунктуацией', () => {
    const out = sanitizeCitations(
      'ты откладываешь деньги [«Новая копилка», 18.09.2026], репетируешь разговор [«Разговор», 28.09.2026]',
      IDS,
    );
    expect(out).toBe('ты откладываешь деньги, репетируешь разговор');
    expect(out).not.toContain('  ');
    expect(out).not.toContain('[');
  });

  it('признанная ссылка остаётся, выдуманная — нет', () => {
    expect(sanitizeCitations(`про бег [#${REAL}]`, IDS)).toBe(`про бег [#${REAL}]`);
    expect(sanitizeCitations('про бег [#local_fakeid123]', IDS)).toBe('про бег');
  });

  // R-2 (ревью 07.10): модель копирует шапку заметки целиком — вместе с датой.
  // Настоящий id при этом терялся: правило (а) вырезало ссылку полностью.
  it('ссылка со шапочной датой сохраняется, дата убирается', () => {
    expect(sanitizeCitations(`Смотри [#${REAL} · 20261006] — там всё.`, IDS))
      .toBe(`Смотри [#${REAL}] — там всё.`);
    expect(sanitizeCitations('Смотри [#local_fakeid123 · 20261006] — там всё.', IDS))
      .toBe('Смотри — там всё.');
  });

  it('номер импортированной заметки (с точкой) не теряется', () => {
    const ids = [...IDS, '1720194283.716586'];
    expect(sanitizeCitations('Ты писал [#1720194283.716586]', ids)).toBe('Ты писал [#1720194283.716586]');
    expect(sanitizeCitations('Ты писал [#1720194283.716586 · 20261006]', ids)).toBe('Ты писал [#1720194283.716586]');
    expect(sanitizeCitations('Ты писал [#1720194283.716586]', IDS)).toBe('Ты писал');
  });

  it('[из заметок] и [источник: …] — тоже выдумка', () => {
    expect(sanitizeCitations('план [из заметок] на неделю', IDS)).toBe('план на неделю');
    expect(sanitizeCitations('цифры [источник: апрель]', IDS)).toBe('цифры');
  });

  it('markdown-ссылка, чекбокс и латинская сноска не тронуты', () => {
    const md = 'посмотри [описание](https://example.com/a) и выбери:';
    expect(sanitizeCitations(md, IDS)).toBe(md);
    const task = '- [ ] сделать забег\n- [x] план';
    expect(sanitizeCitations(task, IDS)).toBe(task);
    const en = 'see [1] and [2] for the run plan';
    expect(sanitizeCitations(en, IDS)).toBe(en);
  });
});

describe('Q-8 (в): ссылка на заметку по названию', () => {
  it('названия, которого нет ни в ходах, ни в материалах, быть не должно', () => {
    const out = sanitizeCitations(
      'в заметке «Письмо маме» ты пишешь про отпуск',
      IDS,
      ['Вечер с мамой'],
      'про работу и планы',
    );
    expect(out).toContain('заметке про Письмо маме');
    expect(out).not.toContain('«Письмо маме»');
  });

  it('настоящий заголовок хода остаётся как есть', () => {
    const src = 'в заметке «Письмо маме» ты пишешь про отпуск';
    expect(sanitizeCitations(src, IDS, ['Письмо маме', 'Вечер с мамой'], 'план на неделю')).toBe(src);
  });

  it('без списка названий правило не применяется (старые вызовы)', () => {
    const src = 'в заметке «Письмо маме» всё ровно';
    expect(sanitizeCitations(src, IDS)).toBe(src);
  });

  // R-1 (ревью 07.10): «в заметке "…"» — ещё и обычная форма цитаты. Пока текст
  // в ёлочках есть в материалах хода, это не выдумка, и переписывать его нельзя.
  it('цитата из материалов остаётся цитатой, а не «про …»', () => {
    const titles = ['Письмо маме'];
    const materials = 'Заметка 1: "Письмо маме"\nВчера снова легла в первом часу.\n— — —\nпереезжай ко мне, он сказал';
    const a = 'В заметке «снова легла в первом часу» есть усталость.';
    const b = 'В записи «переезжай ко мне» слышна мама.';
    expect(sanitizeCitations(a, IDS, titles, materials)).toBe(a);
    expect(sanitizeCitations(b, IDS, titles, materials)).toBe(b);
  });

  it('без материалов правило (в) молчит', () => {
    const src = 'В заметке «снова легла в первом часу» есть усталость.';
    expect(sanitizeCitations(src, IDS, ['Письмо маме'])).toBe(src);
  });

  it('название приложенной заметки из маркера хода не переписывается', () => {
    // форма руками намеренно: санитайзер получает произвольный текст материалов.
    const materials = '[#attached-note · 20261006]\n[Прикреплена заметка: "Бег по утрам"]\n\nПервая пробежка за неделю.';
    const src = 'в заметке «Бег по утрам» ты пишешь про погоду';
    expect(sanitizeCitations(src, IDS, ['Другая запись'], materials)).toBe(src);
  });

  // П5 (самопроверка): без левой границы маска ловила «запис» внутри чужих слов.
  it('часть слова не является упоминанием заметки', () => {
    const src = 'В предзаписи «черновик» ничего не осталось';
    expect(sanitizeCitations(src, IDS, ['Что-то другое'], 'материалы без этого слова')).toBe(src);
  });
});

describe('Q-8 (б): приписанная цитата без опоры', () => {
  const ANSWER = 'ты пишешь «я больше так не могу и не хочу» — и замолкаешь';

  it('нет в материалах — кавычки сняты, текст оставлен', () => {
    expect(sanitizeCitations(ANSWER, IDS, [], 'про работу и планы')).toBe('ты пишешь, по смыслу: я больше так не могу и не хочу — и замолкаешь');
  });

  it('есть в материалах — кавычки на месте', () => {
    expect(sanitizeCitations(ANSWER, IDS, [], 'вчера: «Я больше так не могу и не хочу»')).toBe(ANSWER);
  });

  // MD-3 (0.9.38) снял исключение для гипотез: на стенде недословной считается
  // любая цитата от 4 слов, а кавычки вокруг выдуманной формулировки читатель
  // принимает за слова человека. Кавычки уходят, слова остаются. Короткие метки
  // (1–3 слова) по-прежнему не трогаются — кроме поданных как слова человека
  // («ты пишешь «…»»): с 0.9.41 они сверяются, как длинные (находки 10.6, 11.3).
  it('короткая метка не тронута, короткие «слова человека» и гипотеза — без кавычек', () => {
    expect(sanitizeCitations('это «не могу»', IDS, [], 'пусто')).toBe('это «не могу»');
    expect(sanitizeCitations('ты пишешь «не могу»', IDS, [], 'пусто')).toBe('ты пишешь, по смыслу: не могу');
    const hedge = 'может быть, внутри звучит «я больше так не могу и не хочу» — так?';
    // DY4 (15.1): гипотеза модели — не пересказ, метку не получает.
    expect(sanitizeCitations(hedge, IDS, [], 'пусто'))
      .toBe('может быть, внутри звучит я больше так не могу и не хочу — так?');
  });

  it('регистр, ё и пунктуация при сверке не важны', () => {
    expect(sanitizeCitations(ANSWER, IDS, [], 'Я БОЛЬШЕ ТАК НЕ МОГУ, И НЕ ХОЧУ!')).toBe(ANSWER);
  });
});

describe('Q-8: потоковый текст', () => {
  it('незакрытая скобка и незакрытая кавычка переживают чанк', () => {
    expect(sanitizeCitations('ты пишешь «я больше так', IDS, [], 'пусто')).toBe('ты пишешь «я больше так');
    expect(sanitizeCitations('копилка [«Новая', IDS, [], 'пусто')).toBe('копилка [«Новая');
  });

  it('после закрытия правило применяется', () => {
    expect(sanitizeCitations('копилка [«Новая», 18.09]', IDS, [], 'пусто')).toBe('копилка');
  });
});

// R-1: список названий хода был неполон — приложенная заметка и шапка сравнения
// периодов в него не попадали, и законное название считалось выдумкой.
describe('R-1: названия, которые модель видела в ходе', () => {
  it('маркер приложенной заметки', () => {
    expect(extractContextTitles('[Прикреплена заметка: "Бег"]')).toEqual(['Бег']);
    expect(extractContextTitles('[Прикрепленная заметка: "Бег по утрам"]')).toEqual(['Бег по утрам']);
  });

  it('шапка сравнения периодов — без номера', () => {
    expect(extractContextTitles('[#x · 20261001] Заметка "Бег": текст')).toEqual(['Бег']);
  });

  it('нумерованная шапка результата поиска работала и раньше', () => {
    expect(extractContextTitles('Заметка 1: "Бег"\nдалее тело')).toEqual(['Бег']);
  });
});
