// MD-3 (0.9.38) на уровне клиента: правило применяется в sanitizeCitations и не
// ломает соседние правила. Фикстуры синтетические.
import { describe, expect, it } from 'vitest';
import { sanitizeCitations } from '../useAIChat';

const IDS = ['local_v102'];

const MATERIALS = [
  '[Сегодня: воскресенье, 11 октября 2026]',
  '',
  '[#local_v102 · 20261009]',
  '[Прикрепленная заметка]',
  'Вечером Соня сказала: «Я не хочу, чтобы она возненавидела музыку из-за меня».',
  '',
  '[#local_k07 · 20260928] Строки фона: за три дня до этой записи взяли скрипку напрокат.',
  '',
  'Результаты поиска по архиву заметок (запрос: "скрипка"). Найдено заметок: 1 (отобрано 1).',
].join('\n');

describe('MD-3: sanitizeCitations снимает кавычки с того, чего нет в материалах', () => {
  it('дословная цитата в других кавычках и с переносом строки остаётся', () => {
    const answer = 'Соня ответила “я не хочу, чтобы она\nвозненавидела музыку из-за меня».';
    expect(sanitizeCitations(answer, IDS, [], MATERIALS)).toBe(answer);
  });

  it('пересказ в кавычках теряет кавычки, слова остаются', () => {
    expect(sanitizeCitations('Соня боится «она сорвётся на дочку снова», и молчит.', IDS, [], MATERIALS))
      .toBe('Соня боится: она сорвётся на дочку снова, и молчит.');
  });

  it('цитата из строки фона — она в материалах', () => {
    const answer = 'Позже: «взяли скрипку напрокат».';
    expect(sanitizeCitations(answer, IDS, [], MATERIALS)).toBe(answer);
  });

  it('свои слова человека из этого хода остаются', () => {
    const withUser = `${MATERIALS}\n\nТы написала: «держись, разберёмся в четверг».`;
    const answer = 'Ты ей: «держись, разберёмся в четверг».';
    expect(sanitizeCitations(answer, IDS, [], withUser)).toBe(answer);
  });

  it('правило молчит без материалов', () => {
    const answer = 'Она сказала «ничего не помню про тот четверг».';
    expect(sanitizeCitations(answer, IDS, [])).toBe(answer);
  });

  // Взаимодействие с (в): название несуществующей заметки переписывается маской,
  // и кавычки уже не нужны — правка не должна применяться дважды.
  it('название заметки, которого нет в ходе, переписывает правило (в)', () => {
    const out = sanitizeCitations('в заметке «Письмо маме про отпуск» ты пишешь про море', IDS, ['Вечер с мамой'], MATERIALS);
    expect(out).toContain('заметке про Письмо маме про отпуск');
    expect(out).not.toContain('«');
  });

  it('ссылка хода рядом с цитатой не трогается', () => {
    const out = sanitizeCitations('«Этого в заметке нет вовсе», и вот [#local_v102].', IDS, [], MATERIALS);
    expect(out).toBe('Этого в заметке нет вовсе, и вот [#local_v102].');
  });
});
