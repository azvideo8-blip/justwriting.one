// ED-1 (0.10.7, регрессия DG-3): Редактор предлагает строки от лица автора —
// «я/мой», и страж MD-3 вешал на них «по смыслу», будто слова автора переданы
// неточно. Фикстуры синтетические: ни строки из живого архива.
import { describe, expect, it } from 'vitest';
import { sanitizeCitations } from '../useAIChat';

const IDS = ['local_v102'];

// Ни одна из фраз, которые Редактор предлагает в тестах, в материалах не лежит.
const MATERIALS = [
  '[Сегодня: четверг, 22 октября 2026]',
  '',
  '[#local_v102 · 20261020]',
  '[Прикрепленная заметка]',
  'Вечером Соня сказала: «Я не хочу, чтобы она возненавидела музыку из-за меня».',
  '',
  'Результаты поиска по архиву заметок (запрос: "скрипка"). Найдено заметок: 1 (отобрано 1).',
].join('\n');

const EDITOR_PROPOSAL = 'Другая первая строка: «Я долго не решался написать этот пост».';

describe('ED-1: Редактору «по смыслу» — только по глаголу речи', () => {
  it('(а) своя строка от первого лица без метки, кавычки снимаются как раньше', () => {
    expect(sanitizeCitations(EDITOR_PROPOSAL, IDS, [], MATERIALS, { personaId: 'editor' }))
      .toBe('Другая первая строка: Я долго не решался написать этот пост.');
  });

  it('(б) чужая реплика после глагола речи — метка остаётся', () => {
    expect(sanitizeCitations('она сказала: «мне страшно туда возвращаться».', IDS, [], MATERIALS, { personaId: 'editor' }))
      .toBe('она сказала, по смыслу: мне страшно туда возвращаться.');
  });

  it('(в) у психолога та же строка от первого лица — метка, как в 0.10.7', () => {
    expect(sanitizeCitations(EDITOR_PROPOSAL, IDS, [], MATERIALS, { personaId: 'cbt' }))
      .toBe('Другая первая строка, по смыслу: Я долго не решался написать этот пост.');
  });
});

// ED-1 п.2: ход мыслей — черновик модели, а не ответ. Кавычки не снимать и меток
// не вставлять ни у какой персоны; ссылки [#id] чистить по-прежнему.
// Мутация: вернуть стража в ход мыслей → красный.
describe('ED-1: ход мыслей без стража кавычек', () => {
  it('(г) цитата от первого лица не из материалов не трогается, [#id] чистится', () => {
    const reasoning = 'Черновик: взять «я долго не решался написать этот пост» и убрать [#local_x999].';
    expect(sanitizeCitations(reasoning, IDS, [], MATERIALS, { reasoning: true }))
      .toBe('Черновик: взять «я долго не решался написать этот пост» и убрать.');
  });
});
