/**
 * П-5 (замер 08.10.2026): формы русского имени для поиска по архиву.
 *
 * Прод искал имя как «граница + Имя + граница», то есть только именительный
 * падеж: «что я писал про Марину» не находило запись, где имя стоит в творном
 * («с Мариной»). По замеру на согласованном корпусе именительный видел 64
 * помеченные заметки из 73 (87 %), а по всему корпусу — 277 из 420 (66 %).
 *
 * Словарь форм из архива (первоначальный вариант Р-4) не делаем: он клал бы
 * данные пользователя в индекс и требовал переиндексации. Здесь — чистая
 * функция по окончаниям, без зависимостей и без данных.
 *
 * Два правила, каждое под своим тестом:
 *  1) если форма кончается на известное падежное окончание, оно снимается, а
 *     основа получает все окончания сразу. Без этого «про Марину» не находит
 *     «с Мариной»: имя из реплики приходит в том падеже, в котором его
 *     написали. Таблицы окончаний из тикета (-а/-я, -ий, -ь) эта ветка покрывает
 *     целиком: каждое их окончание есть в общем списке, а написанная форма
 *     восстанавливается тем же хвостом, что снят;
 *  2) финаль не похожа ни на одно окончание — форма и есть основа, и окончания
 *     берёт согласные: «Марат» → «Марата», «Марату», «Маратом». Без этой строки
 *     имена на согласную стоят как написаны и больше никак.
 *
 * Плюс беглая гласная (Лев → Льва) и пустое окончание только для длинной основы
 * на согласную. Граница слова — кириллическая: ascii-граница для кириллицы не
 * матчится. Регистр учитывается: форма ищется с заглавной, потому что строчные
 * «марта», «дашборд», «день» — обычные слова, а не имя.
 *
 * Известные пробелы (в согласованном корпусе не встречаются, в приёмку не
 * входят): притяжательные («Даша» не ловит «Дашин»), множественные («Оли» как
 * «несколько Оль»), нерегулярные основы («Любовь» → «Любви»), «е» вместо «ё»
 * («Фёкла» не ловит «Феклу»), отчества («Игорь» не ловит «Игоревич»).
 *
 * В-4 (ревью 08.10.2026), «Ян» и другие имена из двух букв — пробел оставлен
 * намеренно. Ослабить только порог длины здесь безопасно и даже не нужно для
 * самого «Яна»: проверка ловит «Яну», «Яна», «Яном», «Яны» — и не ловит
 * «Янтарь», «в январе», «Яндекс», «Янович». Но в прод двухбуквенное имя сюда не
 * доходит и с этим порогом: имена вырезаются из запроса и из реплики регулярками
 * по три буквы минимум — `[А-ЯЁ][а-яё]{2,}` в `aiChatContext.ts` и `NAME_RE` в
 * `personQuotes.ts`. Значит, чинить надо их, а это приводит в канал имён слова
 * «Вы», «Ты», «Их», «Оба», «Тот», «Мой» — они пишутся с заглавной в начале
 * фразы, а у канала имён в `aiChatContext` стоп-листа нет (в `personQuotes`
 * есть, и он держит только начало фразы). Имя из двух букв в архиве — редкость,
 * мусор от местоимений в каждом втором запросе — нет. Правка возможна вместе со
 * стоп-листом канала и замером, не одной строкой.
 */

const LEFT = '(?:^|[^а-яёА-ЯЁ])';
const RIGHT = '(?![а-яё])';

/** Никогда не матчится: заглушка, когда вход на имя не похож. */
export const NEVER_MATCH: RegExp = /(?!)/;

// Окончания формы на согласную: сама форма + косвенные падежи (строка тикета).
const CONSONANT_ENDINGS = '|а|у|ом|е|ы|ов';

// Падежные хвосты, которые снимаются с формы из запроса, чтобы получить основу.
// Длинные раньше коротких: иначе «Мариной» потеряется на «й».
const TAILS = [
  'ей', 'ой', 'ою', 'ею', 'ём', 'ёй', 'ий', 'ья', 'ем', 'ом', 'ов',
  'а', 'я', 'ы', 'и', 'е', 'у', 'ю', 'ё', 'ь', 'й',
];

// Все окончания основы. Пустое (= сама основа, именительный) разрешено только
// длинной основе на согласную: иначе «Соня» ловила бы обычное слово «Сон».
const ANY_ENDING = 'а|я|ы|и|е|у|ю|ё|ой|ей|ою|ею|ём|ёй|ий|ья|ь|й|ем|ом|ов';
const FIRM_CONSONANT = /[бвгдзжклмнпрстфхцчшщ]$/;

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function capitalize(s: string): string {
  return s ? s.charAt(0).toUpperCase() + s.slice(1) : s;
}

/**
 * Основы: сама основа плюс варианты с беглой гласной (Лев → Льва,
 * Павел → Павла). Беглая ветка только для имён из 3–5 букв и только перед
 * последней согласной: дальше риск поймать обычное слово выше, чем выгода от
 * одного падежа.
 */
function basesOf(stem: string, nameLength: number): string[] {
  const out = [stem];
  const m = /^(.*)([её])([бвгдзкстфлрмнпцв])$/.exec(stem);
  if (m && nameLength >= 3 && nameLength <= 5) {
    const [, head, , last] = m;
    out.push(`${head}${last}`, `${head}ь${last}`);
  }
  return [...new Set(out)];
}

/**
 * Основы со снятым падежным хвостом: не больше двух — от самого длинного хвоста
 * и от самого короткого. «Илья» даёт и «ил», и «иль», а творный («Ильём») живёт
 * только на второй из них.
 */
function coresOf(lower: string): string[] {
  const hits: string[] = [];
  for (const tail of TAILS) {
    if (!lower.endsWith(tail)) continue;
    const core = lower.slice(0, -tail.length);
    if (core.length >= 2 && !hits.includes(core)) hits.push(core);
    if (hits.length === 2) break;
  }
  return hits;
}

/**
 * Регулярка, ловящая имя в косвенных падежах. Вход, не похожий на кириллическое
 * имя с заглавной буквы, даёт заглушку, которая не матчится никогда: лучше
 * пропустить падеж, чем поймать мусор.
 */
export function nameForms(name: string): RegExp {
  const n = (name ?? '').trim();
  if (!/^[А-ЯЁ][а-яё]{2,}$/.test(n)) return NEVER_MATCH;
  const low = n.toLowerCase();
  const cores = coresOf(low);

  // Семейства: основа + её окончания. Пустая строка endings означает «только
  // сама основа».
  const families: Array<{ stem: string; endings: string }> = [];
  if (cores.length === 0) {
    families.push({ stem: low, endings: CONSONANT_ENDINGS });
  }
  for (const core of cores) {
    const nominative = core.length >= 4 && FIRM_CONSONANT.test(core);
    families.push({ stem: core, endings: `${nominative ? '|' : ''}${ANY_ENDING}` });
  }

  const bodies = families
    .flatMap(({ stem, endings }) => basesOf(stem, n.length).map(b => `${escapeRe(capitalize(b))}(?:${endings})`));
  return new RegExp(`${LEFT}(?:${bodies.join('|')})${RIGHT}`);
}
