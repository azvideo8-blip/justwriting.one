/**
 * Режим хода, когда у диалога есть заметка-тема (приложена сейчас или раньше).
 *
 * 'note' — ответ только по этой заметке: без поиска, хронологии, «недавнего» и
 * цитат памяти. Раньше всё это запускалось по тексту самой заметки, и модель
 * выдавала цитаты из других записей за текст приложенной.
 * 'wide' — пользователь спросил о связях с другими записями.
 */
export type TurnScope = 'note' | 'wide';

// ponytail: словарь маркеров, не классификатор. Промах безопасен: строгий ответ
// предлагает посмотреть в других записях (кнопка под ответом).
//
// DLG-Q7 (Fable T-11): просьбы о других записях. Владелец писал «поищи похожие
// темы» и «другие заметки ещё посмотри» — оба хода оставались строгими, поиск
// не запускался вовсе, и Редактор честно отвечал «по этому запросу ничего не
// нашлось». Консервативность важна: «разбери эту заметку», «что тут главное»,
// «сделай пост» обязаны остаться 'note'.
// П4 (самопроверка): «похож» перечислен формами, как в словаре просьбы
// (`aiChatTransport`), иначе оговорка «похоже, я опять задержалась» срывала
// строгий ход; и архивом считаются не только «в других записях», но и «в старых
// записях», «по прошлым заметкам» — любое одно слово между предлогом и
// существительным, кроме указательного.
// S-1 (ревью 2): блоккер — прежняя форма допускала ЛЮБУЮ форму слова про запись,
// и «сделай пост по моей записи», «что главное в сегодняшней заметке?» становились
// широким ходом: из строгого режима уходили поиск, «недавнее» и память, и модель
// начинала приписывать приложенной заметке чужие цитаты (S-56, R3/R4). Речью об
// архиве считается только множественное число («в старых записях», «по прошлым
// заметкам») или архивные слова (дневник, архив, база). Одна конкретная запись —
// «моей», «сегодняшней», «последней», «этой» — это приложенная заметка.
const ARCHIVE_MENTION = new RegExp(
  '(?:^|[^а-яёА-ЯЁ])(?:в|во|по)\\s+(?!(?:эт[а-яё]*|т[аое](?![а-яё])|той|тех|тем|тот|того|тому|том)\\s)'
  + '(?:\\S+\\s+)?(?:заметках|заметкам|заметками|записях|записям|записями|дневник[а-яё]*|архив[а-яё]*|баз[а-яё]*)'
  // DR-1: «с прошлыми записями» — тот же разговор об архиве, что «из прошлых
  // записей»; предлога `с` в этом словаре не было.
  + '|(?:^|[^а-яёА-ЯЁ])(?:из|со|с)\\s+(?:вс[еюяё]х|разны[х]|проч[а-яё]*|любы[х]|стары[х]|прошл[а-яё]*|прежни[х]|друг[а-яё]*)\\s+(?:замет[а-яё]*|запис[а-яё]*)(?![а-яё])',
  'i',
);
const OTHER_NOTES = new RegExp(
  '(?:^|[^а-яёА-ЯЁ])друг(?:ие|их|им|ими)(?:\\s+\\S+){0,2}\\s+(?:заметк|заметок|запис)'
  + '|(?:заметк|заметок|запис)(?:\\s+\\S+){0,2}\\s+друг(?:ие|их|им|ими)'
  + '|(?:^|[^а-яёА-ЯЁ])ещ[её]\\s+(?:\\S+\\s+){0,2}?(?:заметк|заметок|запис)',
  'i',
);
// DR-1: «свяжи с …» — просьба связать с ДРУГОЙ записью, но только когда она
// названа: «свяжи эти мысли в пост», «свяжи абзацы» остаются строгими (S-1).
// Только множественное число: единичная запись с определителем — это
// приложенная заметка.
const RELATION_VERB_AT_ARCHIVE = /свяж[а-яё]*(?:\s+\S+){0,3}\s+(?:замет(?:ок|ках|кам|ками)|запис(?:ей|ях|ям|ями))/i;
const RELATION_MARKERS = /связ(?:[аиоьы]|ях|ям|ями)|сравн|раньше|как обычно|повторя|паттерн|на эту тему|из других|похож(?:ее|ей|ие|ых|им|ая|ую|его|ему|ем|ею)/i;

// Просьба поискать в записях вообще: гламотряд + «заметк|запис» рядом.
const ASKS_NOTE_SEARCH = /(?:поищи|поиск|найди|найти|посмотри|посмотреть|погляди|глянь|вспомни|проверь|ещ[её])\s+(?:\S+\s+){0,3}?(?:заметк|заметок|запис)/i;
// …но указание на ЭТУ заметку («посмотри эту заметку») — не просьба об архиве.
const POINTS_AT_THIS_NOTE = /эт(?:у|ой|а)\s+заметк/i;

export function turnScope(question: string, opts?: { forceWide?: boolean | undefined }): TurnScope {
  if (opts?.forceWide) return 'wide';
  if (RELATION_MARKERS.test(question) || ARCHIVE_MENTION.test(question) || OTHER_NOTES.test(question)
    || RELATION_VERB_AT_ARCHIVE.test(question)) return 'wide';
  if (ASKS_NOTE_SEARCH.test(question) && !POINTS_AT_THIS_NOTE.test(question)) return 'wide';
  return 'note';
}
