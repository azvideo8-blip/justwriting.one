// MD-4 (0.9.38): плашка Редактора «в посте остались слова другого человека».
// LD-1 и DR-5 смотрят на маркер слова (клиент, терапия); здесь — дословная чужая
// реплика, которая живёт и без таких слов. Плашка ничего не вырезает.
// Фикстуры синтетические: выдуманные имена и сюжеты.
import { describe, expect, it } from 'vitest';
import { diffPostAgainstNote } from '../editorDiff';

const plate = (post: string, source: string) => diffPostAgainstNote(post, source).foreignSpeechInPost;

const NOTE = [
  'Четверг, конец дня.',
  '',
  'Мама Артёма попросила десять минут после урока и сказала: «Я боюсь, что он бросит играть, как я в четырнадцать». Потом добавила: «Я давлю на него, потому что боюсь».',
  '',
  'Я сказала, что он сам выбирает ноты и смеётся над ними. Это правда.',
  '',
  'Вечером думала про себя: меня тоже заставляли, и я до сих пор не знаю, цена это или подарок.',
].join('\n');

describe('MD-4: плашка о чужих словах', () => {
  it('пост, в котором осталась реплика родительницы, подсвечен', () => {
    const post = 'Родитель приходит после урока и говорит: я боюсь, что он бросит играть, как я в четырнадцать. Слышу в этом себя.';
    expect(plate(post, NOTE)).toBe(true);
  });

  it('пост только словами автора — плашки нет', () => {
    const post = 'Он сам выбирает ноты и смеётся над ними. А я до сих пор не знаю, цена это или подарок.';
    expect(plate(post, NOTE)).toBe(false);
  });

  it('пересказ чужой реплики своими словами — плашки нет', () => {
    const post = 'Маме важно, чтобы сын не повторил её путь; она торопит, потому что боится.';
    expect(plate(post, NOTE)).toBe(false);
  });

  it('чужих кавычек в заметке нет — плашка не появляется', () => {
    expect(plate('Сегодня весь день — отчёты, и ни одной живой паузы.', 'Весь день ушёл на отчёты, пауз не было.')).toBe(false);
  });

  it('плашка живёт независимо от имён, ролей и чисел', () => {
    const d = diffPostAgainstNote('Она сказала: я давлю на него, потому что боюсь.', NOTE);
    expect(d.foreignSpeechInPost).toBe(true);
    expect(d.clientStoryInPost).toBe(false);
    expect(d.namesKept).toEqual([]);
  });

  // Кавычки в посте — не условие: важны четыре слова подряд из чужой реплики.
  it('без кавычек в посте попадание всё равно считается', () => {
    expect(plate('Фраза, которую слышу каждую неделю: давлю на него потому что боюсь.', NOTE)).toBe(true);
  });
});
