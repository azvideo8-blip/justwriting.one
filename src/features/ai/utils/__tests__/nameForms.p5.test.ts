// П-5: формы имени по окончаниям — без словаря, собранного из архива.
//
// Мутации, проверенные посадкой (красным на каждой):
//   1) снять кириллическую правую границу `(?![а-яё])` → «Олег» матчится именем
//      «Оля», «Маратович» — именем «Марат»;
//   2) добавить флаг `i` → матчится строчная форма в заметке («с олей»);
//   3) снять проверку «вход похож на имя» → формы получает строчное «марта»;
//   4) убрать согласную строку → не находится «Маратом»;
//   5) убрать снятие хвоста (coresOf) → «про Олю» видит только «Олю» и не находит
//      «Олей», а «Любовь» не находится вовсе;
//   6) выключить беглую гласную → не находятся «Льва» и «Павла»;
//   7) разрешить пустое окончание любой основе → имя «Соня» ловит слово «Сон»;
//   8) убрать «ь» из общего списка окончаний → не находится «Любовь».
// Таблицы окончаний из тикета (-а/-я, -ий, -ь) свёрнуты в одну: ветка снятия
// хвоста покрывает их целиком, и отдельной строки каждая не требует.
import { describe, it, expect } from 'vitest';
import { NEVER_MATCH, nameForms } from '../nameForms';

const hit = (name: string, text: string): boolean => nameForms(name).test(text);

describe('nameForms: косвенные падежи', () => {
  it('имена на -а/-я: падежные формы находятся', () => {
    for (const form of ['Оля', 'Оли', 'Оле', 'Олю', 'Олей']) {
      expect(hit('Оля', `говорили с ${form} вечером`), form).toBe(true);
    }
    expect(hit('Даша', 'позвонил Дашей, а не Даше')).toBe(true);
    expect(hit('Даша', 'обещал Дашу не трогать')).toBe(true);
    expect(hit('Маша', 'вопрос к Маши')).toBe(true);
    expect(hit('Илья', 'мы говорили с Ильи вечером')).toBe(true);
    expect(hit('Илья', 'позвонили Илье')).toBe(true);
    expect(hit('Илья', 'разговор был с Ильём')).toBe(true);
  });

  it('мужские имена: на согласный, на -ий и на -ь', () => {
    expect(hit('Марат', 'договорились с Маратом')).toBe(true);
    expect(hit('Марат', 'позвонили Марату')).toBe(true);
    expect(hit('Марат', 'это Марата идея')).toBe(true);
    expect(hit('Тимур', 'без Тимура не выйдет')).toBe(true);
    expect(hit('Виталий', 'написали Виталию')).toBe(true);
    expect(hit('Виталий', 'спросили Виталия')).toBe(true);
    expect(hit('Виталий', 'речь о Виталии')).toBe(true);
    expect(hit('Виталий', 'доволен Виталием')).toBe(true);
    expect(hit('Игорь', 'позвонили Игоря домой')).toBe(true);
    expect(hit('Игорь', 'договорились с Игорем')).toBe(true);
    expect(hit('Игорь', 'Игорю не позвонишь')).toBe(true);
    expect(hit('Денис', 'поговорили с Денисом')).toBe(true);
    expect(hit('Николай', 'письмо Николаю')).toBe(true);
    expect(hit('Николай', 'встретились с Николаем')).toBe(true);
  });

  it('беглая гласная: Лев → Льва, Павел → Павла', () => {
    expect(hit('Лев', 'рассказывали Льву')).toBe(true);
    expect(hit('Лев', 'не было Льва')).toBe(true);
    expect(hit('Лев', 'ждём Лву')).toBe(true);
    expect(hit('Павел', 'ждём Павла в четверг')).toBe(true);
    expect(hit('Павел', 'договорились с Павлом')).toBe(true);
  });

  it('написанная форма находится всегда: «Любовь» не собирается ни из одного хвоста', () => {
    expect(hit('Любовь', 'это была Любовь')).toBe(true);
    expect(hit('Любовь', 'спросил у Любовь тихо')).toBe(true);
  });

  it('имя из запроса может стоять в косвенном падеже: форма → основа → все формы', () => {
    // Это и есть прод-случай: «что я писал про Олю», где в заметке только «Олей».
    expect(hit('Олю', 'мы говорили с Олей')).toBe(true);
    expect(hit('Олю', 'Оля молчала')).toBe(true);
    expect(hit('Дашу', 'позвонил Даше')).toBe(true);
    expect(hit('Игоря', 'Игорь заходил')).toBe(true);
    expect(hit('Виталия', 'Виталий заходил')).toBe(true);
    expect(hit('Марата', 'Марат заходил')).toBe(true);
    expect(hit('Ильёй', 'Илья заходил')).toBe(true);
  });
});

describe('nameForms: защита от мусора', () => {
  it('чужие слова не матчатся', () => {
    // строчная буква — не имя
    expect(hit('Марат', 'пришёл после марта')).toBe(false);
    expect(hit('Даша', 'открыл дашборд')).toBe(false);
    // «Олег» — другое имя: правая граница не даёт окончиться на «Оле» внутри него
    expect(hit('Оля', 'Олег пришёл')).toBe(false);
    expect(hit('Даша', 'Дашборд обновили')).toBe(false);
    expect(hit('Даша', 'Дальше не пойдёт')).toBe(false);
    expect(hit('Виталий', 'Витрина блеклая')).toBe(false);
    // отчество — не имя из запроса
    expect(hit('Игорь', 'Игоревич поздоровался')).toBe(false);
    // длинное слово, начинающееся с формы имени
    expect(hit('Марат', 'Маратович поздоровался')).toBe(false);
    expect(hit('Настя', 'Настойка на травах')).toBe(false);
    // обычное слово, совпадающее с основой: «Сон» не форма имени «Соня»
    expect(hit('Соня', 'Сон приснился')).toBe(false);
  });

  it('вход, не похожий на имя, даёт заглушку, которая не матчится никогда', () => {
    const text = 'что угодно Оля Оле';
    for (const bad of ['', '   ', 'ольга', 'О', 'О1', 'Оль-Гад', 'А', 'ё', 'Ёлкой', 'М-1']) {
      expect(nameForms(bad).test(text), bad).toBe(false);
    }
    // Тикетный пример «марта»: строчное слово именем не считается, и оно не
    // получает ни одной формы.
    expect(nameForms('марта').source).toBe(NEVER_MATCH.source);
    expect(NEVER_MATCH.source).toBe('(?!)');
  });

  // В-4 (ревью 08.10.2026): имя из двух букв сюда не доходит — и не из-за
  // окончаний. Порог длины снять можно (ниже видно, что формам «Ян» ничего не
  // мешает), но имена вырезаются из запроса и из реплики регулярками по три
  // буквы минимум, а вместе с двухбуквенными именами в канал имён попадут «Вы»,
  // «Ты», «Их», «Оба». Пин на заглушку — храповик: ослабление порога в
  // `nameForms` обязано сопровождаться стоп-листом канала и замером.
  it('В-4: «Ян» остаётся заглушкой, а формы того же корня ловятся и не цепляют обычные слова', () => {
    expect(nameForms('Ян').source).toBe(NEVER_MATCH.source);
    // Основы того же корня работают, когда имя хотя бы три буквы:
    expect(hit('Яна', 'позвонил Яну')).toBe(true);
    expect(hit('Яна', 'дом Яны')).toBe(true);
    expect(hit('Яна', 'встреча с Яной')).toBe(true);
    // …и не цепляют то, на что указал ревьюер:
    expect(hit('Яна', 'Янтарь лежит')).toBe(false);
    expect(hit('Яна', 'в январе')).toBe(false);
    expect(hit('Яна', 'Яндекс купил')).toBe(false);
    expect(hit('Яна', 'Павел Янович')).toBe(false);
  });

  it('регистр заметки соблюдается: строчная форма не находится', () => {
    expect(hit('Оля', 'мы говорили с олей')).toBe(false);
    expect(hit('Марат', 'звали маратом')).toBe(false);
  });

  it('форма находится в начале строки и после пунктуации', () => {
    expect(hit('Оля', 'Оле позвони')).toBe(true);
    expect(hit('Оля', '— Оле, ты?')).toBe(true);
    expect(hit('Оля', 'спросил (Олю) тихо')).toBe(true);
  });

  it('регулярка не глобальная: повторный test даёт тот же результат', () => {
    const re = nameForms('Оля');
    expect(re.global).toBe(false);
    expect(re.lastIndex).toBe(0);
    expect(re.test('тихо, без имени')).toBe(false);
    expect(re.test('говорили с Олей')).toBe(true);
    expect(re.test('говорили с Олей')).toBe(true);
  });

  it('непустота: у имени на -а находится не меньше четырёх форм', () => {
    const covered = ['Оля', 'Оли', 'Оле', 'Олю', 'Олей'].filter(f => hit('Оля', f));
    expect(covered.length).toBeGreaterThanOrEqual(4);
  });
});
