import { describe, expect, it } from 'vitest';
import { diffPostAgainstNote } from '../editorDiff';
import { SYNTH } from './synthEditorPosts.ed2';

// 3.1 / 18.1(б): в пост Редактора ушло, чего близкие ждут от автора в деньгах.
// Строка в PRIVACY не сдвинула замер (10/10 → 10/10), поэтому — плашка по посту,
// как LD-1: ничего не вырезается, автор решает сам. Признак — в одной фразе поста
// названы близкий (или «дома») и деньги.
// Замер на стенде arch-2026-10-11 (готовые ответы Редактора, 750 постов, без
// новых вызовов): S6d с деньгами близких в посте — 136/136, остальные посты — 0/614.
// Фикстуры синтетические.
//
// Мутации: убрать «дома» из близких → (а) красный; искать по всему посту, а не
// по фразе → (г) красный.

const warns = (post: string) => diffPostAgainstNote(post, 'Синтетическая заметка автора.').relativesMoneyInPost;

describe('3.1: деньги близких в посте', () => {
  it('(а) близкий и деньги в одной фразе — предупреждение', () => {
    expect(warns('Партнёрша считает, что я должен зарабатывать вдвое больше.')).toBe(true);
    expect(warns('Дома сказали: раз ушёл из офиса, денег должно хватать на всех.')).toBe(true);
    expect(warns('Мама до сих пор отдаёт долг за дачу.')).toBe(true);
  });

  it('(б) свои деньги без близких — тихо', () => {
    expect(warns('Я наконец назвал цену своих уроков и выдержал паузу.')).toBe(false);
  });

  it('(в) близкие без денег и похожие слова — тихо', () => {
    expect(warns('Вечером с мамой долго гуляли у реки.')).toBe(false);
    expect(warns('Папка с тетрадями осталась у брата.')).toBe(false);
  });

  it('(г) близкий и деньги в разных фразах — тихо', () => {
    expect(warns('Муж уехал на рыбалку. Я пересчитала деньги до зарплаты.')).toBe(false);
  });

  it('бюджет: 20 синтетических постов ED-2 — ни одного срабатывания', () => {
    expect(SYNTH.filter(([post, source]) => diffPostAgainstNote(post, source).relativesMoneyInPost)).toEqual([]);
  });
});
