import { describe, it, expect } from 'vitest';
import { turnScope } from '../turnScope';

describe('turnScope — вопрос о приложенной заметке', () => {
  it.each([
    'как это связано с отцом?',
    'Сравни с прошлой неделей',
    'было ли так раньше?',
    'это у меня повторяется?',
    'видишь паттерн?',
    'что в других записях про это',
    'посмотри в других заметках',
    'как обычно я на это реагирую?',
    // П4 (самопроверка): архивом считается не только «в других записях».
    'а в старых записях есть что-то про деньги',
    'по прошлым заметкам видно, что я откладываю',
    'во всех записях про этот день',
  ])('широкий ход: %s', q => {
    expect(turnScope(q)).toBe('wide');
  });

  it.each([
    'разбери',
    'Разбери эту заметку',
    'что мне делать с часами?',
    'почему я так злюсь?',
    '',
    // Указательный оборот остаётся строгим: «в этой заметке» — про неё.
    'что в этой заметке главное',
    'в этой записи я путаю даты',
    // П4: оговорка «похоже,» — не просьба об архиве (та же форма, что в словаре
    // просьбы в aiChatTransport).
    'похоже, я опять задержалась',
    'это похоже на прошлый раз',
  ])('строгий ход: «%s»', q => {
    expect(turnScope(q)).toBe('note');
  });

  it('кнопка «Связать с другими записями» делает ход широким', () => {
    expect(turnScope('Разбери эту заметку', { forceWide: true })).toBe('wide');
  });
});
