import { describe, it, expect } from 'vitest';
import { turnScope } from '../turnScope';

describe('turnScope — вопрос о приложенной заметке', () => {
  it.each([
    'как это связано с отцом?',
    'Сравни с прошлой неделей',
    'было ли так раньше?',
    'это у меня повторяется?',
    'видишь паттерн?',
    'что в других записях про это',
    'посмотри в других заметках',
    'как обычно я на это реагирую?',
    // П4 (самопроверка): архивом считается не только «в других записях».
    'а в старых записях есть что-то про деньги',
    'по прошлым заметкам видно, что я откладываю',
    'во всех записях про этот день',
    'в моём дневнике это было?',
    'в старых записях было похожее?',
    // Зонд самопроверки: «собери из всех заметок» — архив, а не одна запись.
    'собери из всех заметок',
    'вытащи цитату из прошлых заметок',
    // DR-1 (находка 7 живого диалога): «свяжи с другими заметками» оставался
    // строгим ходом — поиска не было вовсе, и модель «связывала» по коротким
    // строкам фона, додумывая сцены.
    'свяжи с другими заметками',
    'свяжи это с другими моими записями',
    'свяжи с прошлыми записями',
    'свяжи с моими заметками',
    'подробнее о связях',
    'начни с прошлых записей',
    'расскажи подробнее о связях с другими заметками',
    'о связях с прошлыми записями',
    'какие связи с другими записями',
    'сравни с другими заметками',
  ])('широкий ход: %s', q => {
    expect(turnScope(q)).toBe('wide');
  });

  it.each([
    'разбери',
    'Разбери эту заметку',
    'что мне делать с часами?',
    'почему я так злюсь?',
    '',
    // Указательный оборот остаётся строгим: «в этой заметке» — про неё.
    'что в этой заметке главное',
    'в этой записи я путаю даты',
    // S-1 (ревью 2): единичная запись с определителем — это приложенная заметка,
    // а не архив. Прежняя форма `заметк|запис` уводила эти ходы в широкий режим.
    'сделай пост по моей записи',
    'что главное в сегодняшней заметке?',
    'что в моей заметке не так?',
    'разбери, что в последней записи',
    'собери текст из вчерашней заметки',
    'достань цитату из этой заметки',
    'выпиши фразу из моей записи',
    // П4: оговорка «похоже,» — не просьба об архиве (та же форма, что в словаре
    // просьбы в aiChatTransport).
    'похоже, я опять задержалась',
    'это похоже на прошлый раз',
    // DR-1: глагол «свяжи» сам по себе — про склейку ТЕКСТА приложенной заметки,
    // а не про архив. Широким его делает только названная другая запись.
    'свяжи эти мысли в пост',
    'свяжи абзацы',
    'свяжи два куска в один текст',
    'что главное в этой заметке?',
  ])('строгий ход: «%s»', q => {
    expect(turnScope(q)).toBe('note');
  });

  it('кнопка «Связать с другими записями» делает ход широким', () => {
    expect(turnScope('Разбери эту заметку', { forceWide: true })).toBe('wide');
  });
});
