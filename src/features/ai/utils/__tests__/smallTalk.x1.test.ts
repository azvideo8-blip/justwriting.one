import { describe, it, expect } from 'vitest';
import { isSmallTalkTurn } from '../smallTalk';

// X-1: светский ход не должен получать архив, и ровно поэтому предикат обязан
// промахиваться в сторону «не светский»: вопрос, просьба о поиске, короткое
// сообщение о состоянии — всё это остаётся с контекстом.
describe('X-1: isSmallTalkTurn', () => {
  it.each([
    'привет',
    'Привет!',
    'привет 👋',
    'здравствуйте',
    'доброе утро',
    'как дела',
    'как настроение',
    'что нового',
    'расскажи о себе',
    'что ты умеешь',
    'спасибо',
    'спасибо большое',
    'благодарю',
    'хорошо',
    'пока',
    'hi',
    'hello there',
    'good morning',
    'how are you doing',
    'what s up',
    'thanks a lot',
    'thank you so much',
    'tell me about yourself',
    '...',
    '—',
    '',
  ])('светский: «%s»', (text) => {
    expect(isSmallTalkTurn(text, false)).toBe(true);
  });

  it.each([
    'что я писал вчера?',
    'о чём была моя заметка про утренние пробежки',
    'найди записи про Сашу',
    'вспомни, что я думал про переезд',
    'посмотри в дневнике про март',
    'разбери эту заметку',
    'что было на этой неделе',
    'помоги разобраться с тревогой',
    'мне плохо',
    'устал',
    'страшно',
    'so tired',
    'нужна помощь',
    'как дела с проектом',
    'объясни разницу между виной и стыдом',
    'хочу научиться ложиться вовремя',
  ])('не светский: «%s»', (text) => {
    expect(isSmallTalkTurn(text, false)).toBe(false);
  });

  it('вопрос не спасает от контекста короткой формой', () => {
    // «как дела?» — тот же привет, но правило «любой знак вопроса = не светский»
    // оставлено как было до X-1: промах должен стоить лишних знаков контекста,
    // а не потерянной памяти.
    expect(isSmallTalkTurn('как дела?', false)).toBe(false);
    expect(isSmallTalkTurn('привет, как дела?', false)).toBe(false);
  });

  it('у псих-персон порог длины ниже, а словарь тот же', () => {
    expect(isSmallTalkTurn('привет', true)).toBe(true);
    expect(isSmallTalkTurn('расскажи о себе', true)).toBe(true);
    // Две реплики-слова у терапевта — обычная часть диалога, не светский ход.
    expect(isSmallTalkTurn('что делать', true)).toBe(false);
    expect(isSmallTalkTurn('что делать', false)).toBe(true);
  });
});
