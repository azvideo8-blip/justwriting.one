import { describe, expect, it } from 'vitest';
import { diffPostAgainstNote } from '../editorDiff';

// LD-1: пост Editor'а пересказывает сеанс клиента. PRIVACY Редактора закрывает
// имена, здоровье, деньги и адреса, но не события и слова другого человека в
// уязвимом положении — для автора, который работает с людьми, это врачебная
// тайна. Плашка не вырезает ничего, только поднимает предупреждение.
// Фикстуры синтетические: дневник психолога, которого никто не знает.

const warns = (post: string, source: string) => diffPostAgainstNote(post, source).clientStoryInPost;

describe('LD-1: чужая история в посте', () => {
  it('пост с репликой клиента — предупреждение', () => {
    const source = 'Сегодня на сессии клиентка сказала, что не может отказаться от просьб матери. Я заметил, как сам напрягся.';
    expect(warns('На сессии клиентка сказала: «не могу отказать». Я напрягся.', source)).toBe(true);
  });

  it('маркеры: пациент, терапия, «сессия с», «на сессии»', () => {
    expect(warns('Пациент в конце недели описал то же самое.', 'Пациент описал то же.')).toBe(true);
    expect(warns('После терапии я стал замечать паузы.', 'Вчера был на терапии, заметил паузы.')).toBe(true);
    expect(warns('Сессия с новым человеком показала старую схему.', 'Сессия с новым человеком показала старую схему.')).toBe(true);
    expect(warns('На сессии было тяжело молчать.', 'На сессии было тяжело молчать.')).toBe(true);
  });

  it('пост без таких слов — предупреждения нет', () => {
    const source = 'Утром был длинный созвон с подрядчиком, вечером дописал главу.';
    expect(warns('Созвон затянулся, а глава всё-таки дописана.', source)).toBe(false);
  });

  // Решает пост: чужая история в заметке, которой в посте нет, не шумит.
  it('слово о клиенте только в заметке — предупреждения нет', () => {
    expect(warns('Вечером дописал главу и выдохнул.', 'Клиентка принесла ту же жалобу, что и в мае.')).toBe(false);
  });

  it('своя терапия автора: «мой терапевт» в заметке и нет клиентов — предупреждения нет', () => {
    const source = 'Мой терапевт помогает мне замечать, как я ухожу в шутки.';
    expect(warns('Свою терапию я выбирал полгода.', source)).toBe(false);
  });

  it('«на свою терапию» — тоже своя история', () => {
    const source = 'Записался на свою терапию на четверг.';
    expect(warns('На свою терапию записался на четверг.', source)).toBe(false);
  });

  // Ревёрнутая проверка исключения: рядом с собой у автора есть клиент.
  it('исключение не работает, если в заметке есть клиент', () => {
    const source = 'Мой терапевт говорит не торопиться, а клиентка вчера рассказала про мать.';
    expect(warns('Свою терапию я откладывал три месяца.', source)).toBe(true);
  });

  it('чужая история не зависит от того, есть ли имена в посте', () => {
    const source = 'Клиент принёс на сессию ту же жалобу, что и месяц назад.';
    const d = diffPostAgainstNote('Клиент вернулся с той же жалобой, что месяц назад.', source);
    expect(d.clientStoryInPost).toBe(true);
    // Ни имён, ни ролей, ни чисел: предупреждение должно жить и без плашки сверки.
    expect(d.namesKept).toEqual([]);
    expect(d.namesRemoved).toEqual([]);
    expect(d.rolesAdded).toEqual([]);
    expect(d.numbersRemoved).toEqual([]);
  });
});
