import { describe, it, expect } from 'vitest';
import { detectRisk } from '../riskDetect';

// Исключение (SAFE_CONTEXT) снимает тревогу, только если оно не лежит целиком
// внутри найденной фразы: «не хочу» внутри «не хочу жить» — это и есть риск.
describe('detectRisk', () => {
  it.each([
    'Не хочу жить, всё бессмысленно.',
    'Не хочу жить больше',
    'я просто не хочу жить',
    'хочу покончить с собой',
    'каждую ночь думаю про суицид',
    'нет смысла жить дальше',
    // R3-002: исключение у ранней фразы не прячет острую дальше по тексту.
    'раньше думал о смерти, а сейчас режу себя',
    // R3-003: исключение из соседней клаузы не гасит острое.
    'не думал о смерти, но хочу покончить с собой',
    // R3-025: невидимые символы, ё/е, «дальше».
    'не​ хочу жить',
    'нет смысла дальше жить',
    'это мое последнее письмо',
    'это моё последнее письмо',
    // L-1 (R4-002): «drop»-символ вместо пробела — ZWNJ, ZWJ, BOM.
    'не\u200Cхочу\u200Cжить',
    'хочу\u200Dумереть',
    'не\uFEFFхочу\uFEFFжить',
    // L-1: латинские буквы-двойники.
    'хочу умeрeть',
    // L-1: английский.
    'I want to kill myself',
    'i want to die',
    'suicide',
    // L-1: транслит.
    'ne hochu zhit',
    'hochu umeret',
    'pokonchit s soboj',
    'pokonchit s soboi',
    // M-14: латиница складывается в русские буквы (H→Н), а не в «һ».
    'HE XOЧУ ЖИТЬ',
    'Hе хочу жить',
    // M-15: «not» в той же клаузе, но не при самой фразе — риск остаётся.
    'I am not ok and I want to die',
    // R5-014: серия невидимых символов даёт один разделитель, а не склейку.
    'не\u200B\u200Bхочу\u200Bжить',
    'не\u200B\u200B\u200Bхочу\u200B\u200Bжить',
    'не\u200C\u200Cхочу жить',
    'не\uFEFF\uFEFFхочу\u200B\u200Bжить',
    // R5-014: несовершенный вид и настоящее время.
    'хочу умирать',
    'думаю о том как убить себя',
    'думаю о самоубийстве',
    // «не хочу больше жить» — канонический вариант, мимо которого шёл паттерн.
    'не хочу больше жить',
    'не хочу дальше жить',
    // R5-018: кириллическая «у» внутри EN/транслита.
    'sуicide',
    'hochу umeret',
    // R5-004: «жить так / больше / в этом мире / с этой болью» — острое.
    'не хочу жить больше',
    'не хочу жить так',
    'не хочу жить в этом мире',
    'не хочу жить на этом свете',
    'не хочу жить с этой болью',
    'не хочу жить в страхе',
    // R5-016: «покончить с собой / с жизнью / со всем этим» и боль — острое.
    'хочу покончить со всем этим',
    'хочу покончить с этим',
    'хочу покончить с этим раз и навсегда',
    'хочу покончить с жизнью',
    'хочу покончить',
    'хочу умереть от тоски',
  ])('риск: %s', text => {
    expect(detectRisk(text).isRisk).toBe(true);
  });

  it.each([
    'раньше думал о смерти, но это в прошлом',
    'не планирую ничего с собой делать',
    'я не думал о смерти',
    'я не хочу умереть, я хочу разобраться',
    'всё плохо, я очень устал',
    'была мысль но справляюсь — суицид это не про меня сейчас',
    // R3-026: «яд» внутри «порядок».
    'навести порядок в голове и перестать ругать себя',
    // L-1: средство и цель в разных клаузах — means-паттерн не переходит запятую.
    'врач выписал таблетки, чтобы не умереть',
    // M-15: границы слов и отрицание в EN/транслите.
    'i want to diet',
    "I don't want to kill myself",
    "I'm not going to kill myself",
    'ne hochu umeret',
    // R5-014: отрицание настоящего времени гасит так же, как прошедшего.
    'я не думаю о том как убить себя',
    'не хочу умирать молодым',
    // R5-017: отрицание при самом «kill», а не только при «want/going».
    "i won't kill myself",
    'i will not kill myself',
    "i wouldn't kill myself",
    'it is not that i want to die, but tired',
    // R5-020: «не вариант» в той же клаузе.
    'это не про меня, суицид не вариант',
    // R5-016: бытовые идиомы.
    'хочу покончить с этим проектом',
    'хочу покончить с прокрастинацией',
    'хочу покончить с этим бардаком',
    'хочу умереть от стыда',
    'хочу умереть от смеха',
    // R5-004: место и соседи — не острое.
    'я не хочу жить в этом городе',
    'не хочу жить в общежитии',
    'не хочу жить одна',
    'не хочу жить здесь',
    'не хочу жить с ним',
  ])('не риск: %s', text => {
    expect(detectRisk(text).isRisk).toBe(false);
  });

  // M-16: .* между группами бэктрекал минуты на вырожденном вводе.
  // R5-019: means-паттерн («нож нож …» одной строкой): с [^…]* без предела
  // 100k символов (сообщение + приложенная заметка, aiChatContext.ts) — ~3.5 с,
  // с {0,100} — ~30 мс.
  it.each([
    ['никто не заметит', 'никто не заметит если когда '.repeat(1800)],
    ['средство без цели', 'нож '.repeat(25_000)],
  ])('вырожденный ввод 50–100k символов (%s) — без катастрофического бэктрекинга', (_name, text) => {
    const t0 = performance.now();
    detectRisk(text);
    expect(performance.now() - t0).toBeLessThan(1500);
  });
});
