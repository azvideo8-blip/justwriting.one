import { describe, expect, it } from 'vitest';
import { isProvenanceTurn } from '../aiChatContext';

// К21-1 (случай #21, 21.1 (1)): «откуда ты это взял?» — вопрос о материалах
// прошлого ответа, а не новая тема хода. Список форм короткий: это дословные
// вопросы о происхождении сказанного. Длинная реплика, где «откуда» стоит
// внутри темы («откуда взялась эта привычка»), — не провенанс.
// Формулировки синтетические.
const FORMS = [
  'Откуда ты это взял?',
  'откуда ты это взяла',
  'Откуда ты это взяла?',
  'Это откуда?',
  'а это откуда',
  'Где ты это нашёл?',
  'где ты это нашла',
  'Ты это придумал?',
  'ты это придумала?',
  'На чём основано?',
  'на чем основан этот вывод',
  'Из какой записи?',
  'из какой это заметки',
  'Ну откуда ты это взял',
  // ревью К21: пропуски
  'а откуда ты это знаешь?',
  'это ты сам придумал или из записей?',
  'Слушай, а откуда ты это взял вообще, я такого не писал?',
];

const NOT_PROVENANCE = [
  // «откуда» внутри темы, реплика длиннее порога
  'Расскажи, откуда взялась эта привычка и что я про неё писал в октябре — хочу собрать линию',
  // рамка вопроса на месте, но реплика длинная и со своей темой: такой ход
  // обязан искать по своей теме, а не отвечать только про прошлый
  'Откуда ты это взял? И заодно посмотри, что я писал про утренние страницы в октябре и как это связано с усталостью к среде',
  // короткая реплика с «откуда», но про своё, а не про ответ
  'откуда взялась моя тревога?',
  'где ты был вчера',
  'я придумал название для канала',
  'на чем держится моя дисциплина',
  'из какой страны приехали эти слова про дисциплину и как они связаны с моими записями',
  'привет',
  '',
  // ревью К21: «это откуда» и «ты придумал» внутри своей темы
  'А это откуда у меня такая тревога?',
  'Это откуда во мне, как думаешь?',
  'Ты сочинил стихотворение?',
  'Вы придумали мне план на неделю?',
];

describe('К21-1: распознавание хода о происхождении сказанного', () => {
  it('формы вопроса узнаются, ё/е и регистр не мешают', () => {
    for (const form of FORMS) {
      expect(isProvenanceTurn(form), form).toBe(true);
    }
  });

  it('«не то»: тема с «откуда» внутри и чужие глаголы провенансом не считаются', () => {
    for (const form of NOT_PROVENANCE) {
      expect(isProvenanceTurn(form), form).toBe(false);
    }
  });
});
