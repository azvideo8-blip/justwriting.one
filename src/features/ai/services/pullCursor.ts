// Курсор инкрементального забора — одна формула у фонового прохода и у сетевого
// фузза, который обязан проверять ровно её, а не свою копию.
/**
 * Откуда забирать: строго после курсора, без запаса. И фильтр, и курсор — серверная
 * отметка (0037), сравнивать часы устройств больше нечего. Запас назад (было
 * 30 мин) перекачивал каждый проход всё, что отмечено в его пределах от самой
 * свежей отметки, — после 0037 это весь набор ИИ-записей аккаунта, отмеченный
 * одним моментом миграции, и так до первой новой записи. Цена — строка, чья
 * транзакция началась раньше, а закоммитилась позже уже забранной (now() = старт
 * транзакции): её возьмёт ежедневное полное восстановление.
 */
export function pullSince(cursor: number): number {
  return cursor;
}

/**
 * По часам устройства вести курсор нельзя:
 * устройство с часами вперёд забирает из облака прошлое и никогда не видит чужих
 * будущих правок. Поэтому курсор ползёт вперёд по отметке, реально увидленной в
 * облаке (миграция 0037 ставит её сервер), а часы устройства служат только
 * потолком: серверная отметка не может оказаться новее начала этого прохода.
 */
export function nextPullCursor(startedAt: number, last: number, maxUpdatedAt: number): number {
  return Math.min(startedAt, Math.max(last, maxUpdatedAt));
}
