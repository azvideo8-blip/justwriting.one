import { describe, expect, it } from 'vitest';
import { detectAuthorGender, expandGenderForms, genderByForms } from '../authorGender';

// PR-10 (18.2): род автора — из форм прошедшего времени от первого лица в
// текстах этого хода. Прилагательное «рад» рода не выдаёт.
describe('PR-10: род автора по формам прошедшего времени', () => {
  it('мужской род', () => {
    expect(detectAuthorGender('Вчера я проснулся рано. Я сел у окна. Потом я долго молчал.')).toBe('m');
  });

  it('женский род', () => {
    expect(detectAuthorGender('Вчера я проснулась рано. Я села у окна. Потом я долго молчала.')).toBe('f');
  });

  it('смешанные формы — род не передан', () => {
    expect(detectAuthorGender('Я сказал одно, а потом я сказала другое. Я думал. Я решила.')).toBeNull();
  });

  it('форм нет — род не передан', () => {
    expect(detectAuthorGender('Утро. Тихо. Надо собираться.')).toBeNull();
    expect(detectAuthorGender('')).toBeNull();
    expect(detectAuthorGender(null)).toBeNull();
  });

  it('«рад» сам по себе рода не даёт', () => {
    expect(detectAuthorGender('Я рад. Я рад. Я рад.')).toBeNull();
    expect(detectAuthorGender('Я рада. Я рада. Я рада.')).toBeNull();
    expect(detectAuthorGender('Я был рад этому. Я был рад тому. Я был рад всему.')).toBe('m');
  });

  it('глагол через наречие — всё равно находится', () => {
    expect(detectAuthorGender('Я тогда очень устала. Я тогда очень ждала. Я тогда рано легла.')).toBe('f');
  });

  // Мутация: не вырезать кавычки — красный.
  it('чужая речь в кавычках не в счёт', () => {
    expect(detectAuthorGender('Я пришла. Я села. Я ждала. Он: «я устал», "я заболел", „я уехал“, “я забыл”.')).toBe('f');
  });
});

// Ревью К29: чужое подлежащее, придаточное и существительные на -л — не род автора.
// Мутации: не обрывать окно на знаке / на союзе / на глаголе настоящего — красный.
describe('К29-1: окно «я» обрывается на чужом', () => {
  it.each([
    'Я думаю, он хотел. Я помню, как папа пришёл. Я знаю, что муж устал.',
    'Я рад, что жена пришла. Я рада, подруга звонила. Я тут, она ждала.',
    'Я думаю он хотел. Я помню как папа пришёл. Я рада что муж устал.',
    'Я рад что жена пришла. Я рад что она ждала. Я рад когда мама звонила.',
    'Я вижу стол. Я люблю журнал. Я люблю футбол.',
    'Я\nСделал сам. Я\nПришёл. Я\nУшёл.',
  ])('%s', text => {
    expect(detectAuthorGender(text)).toBeNull();
  });

  it('своё сказуемое через наречия — находится', () => {
    expect(detectAuthorGender('Я наконец-то легла. Я поэтому ушла. Я опять не смогла.')).toBe('f');
    expect(detectAuthorGender('Я никому не сказала. Я ему ответила. Я так и не поняла.')).toBe('f');
  });
});

// К29-1: перевес вместо «ни одной чужой». Мутации: порог 3 → 1; доля 0,8 → 0,9 или 0,5 — красный.
describe('К29-1: перевес форм', () => {
  it.each([
    [16, 0, 'm'], [0, 16, 'f'], [21, 4, 'm'], [4, 21, 'f'], [11, 1, 'm'], [8, 1, 'm'], [4, 1, 'm'], [3, 0, 'm'],
    [0, 0, null], [2, 2, null], [2, 0, null], [0, 1, null], [7, 2, null], [3, 1, null],
  ] as const)('%i м / %i ж → %s', (m, f, want) => {
    expect(genderByForms(m, f)).toBe(want);
  });
});

describe('К29-1: скобка в ответе раскрывается по роду', () => {
  it.each([
    ['Ты сделал(а) это и устал(а).', 'Ты сделал это и устал.', 'Ты сделала это и устала.'],
    ['Ты начал(а), понял(-а) и вспомнил(а).', 'Ты начал, понял и вспомнил.', 'Ты начала, поняла и вспомнила.'],
    ['Ты боялся(ась), собрался(лась), старался(-ась).', 'Ты боялся, собрался, старался.', 'Ты боялась, собралась, старалась.'],
    ['Тебе важно, чтобы сам(а) решал(а).', 'Тебе важно, чтобы сам решал.', 'Тебе важно, чтобы сама решала.'],
    ['Вы сделал(а) паузу.', 'Вы сделал паузу.', 'Вы сделала паузу.'],
    ['Ты пришёл(ла) и ушел(а).', 'Ты пришёл и ушел.', 'Ты пришла и ушла.'],
    ['Ты смог(ла), не мог(ла).', 'Ты смог, не мог.', 'Ты смогла, не могла.'],
    ['Ты должен(на), готов(а), сам(а) уверен(а).', 'Ты должен, готов, сам уверен.', 'Ты должна, готова, сама уверена.'],
    ['Должен(на) ли ты?', 'Должен ли ты?', 'Должна ли ты?'],
  ])('%s', (text, m, f) => {
    expect(expandGenderForms(text, 'm')).toBe(m);
    expect(expandGenderForms(text, 'f')).toBe(f);
  });

  it('род неизвестен — без правки', () => {
    expect(expandGenderForms('Ты сделал(а) это.', null)).toBe('Ты сделал(а) это.');
    expect(expandGenderForms('Ты сделал(а) это.', undefined)).toBe('Ты сделал(а) это.');
  });

  it.each([
    'Ты «сделал(а)» сказал.', 'Ты видишь: пункт (а) и вариант(б).', 'Ты ждёшь, он(а) придёт.', 'Ты читаешь: заметк(а) о доме.',
    'Ты пишешь “сделал(а)”, "устал(а)", „понял(а)“, ‘решил(а)’ и `сам(а)`.',
    'Твой начальник, возможно, сам(а) не понял(а).', 'Ты видишь материал(а) и канал(а).',
    'Ты решил(а)сь.', 'Ты вернул(ась) домой.', 'Ты тут. Начальник сказал(а) это.',
  ])('не тронуто: %s', text => {
    expect(expandGenderForms(text, 'f')).toBe(text);
    expect(expandGenderForms(text, 'm')).toBe(text);
  });

  it('до и после кавычек правится, внутри — нет', () => {
    expect(expandGenderForms('Ты сказал(а): «он сделал(а)» и ушёл(ла).', 'f')).toBe('Ты сказала: «он сделал(а)» и ушла.');
  });
});
