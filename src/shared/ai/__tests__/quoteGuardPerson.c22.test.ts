// Случай #22 (22.3): цитата с переделанным лицом глагола — уже не слова человека,
// кавычки снимаются. Фикстуры синтетические.
// Мутация: снять `personShifted` в «почти дословной» — краснеет «лицо сменено».
import { describe, expect, it } from 'vitest';
import { unquoteAbsent } from '../quoteGuard';

const MATERIALS = [
  '[#local_c22_note · 20261103]',
  '[Прикрепленная заметка]',
  'Я сопротивляюсь этим формулировкам, когда пишу о своих клиентах по вечерам.',
  'Завтра снова поеду в центр и посмотрю расписание групп.',
].join('\n');

describe('22.3: лицо глагола в цитате', () => {
  it('лицо сменено («сопротивляюсь» → «сопротивляешься») — кавычки сняты', () => {
    const answer = 'Ты пишешь: «сопротивляешься этим формулировкам, когда пишу о своих клиентах».';
    const out = unquoteAbsent(answer, MATERIALS);
    expect(out.stripped).toHaveLength(1);
    expect(out.text).not.toContain('«сопротивляешься');
  });

  it('дословная цитата остаётся в кавычках', () => {
    const answer = 'Ты пишешь: «сопротивляюсь этим формулировкам, когда пишу о своих клиентах».';
    expect(unquoteAbsent(answer, MATERIALS).stripped).toHaveLength(0);
  });

  it('огрех в одном слове без смены лица (допуск DY4) — кавычки остаются', () => {
    const answer = 'Ты пишешь: «сопротивляюсь этим формулировкам, когда пишу о моих клиентах».';
    expect(unquoteAbsent(answer, MATERIALS).stripped).toHaveLength(0);
  });

  it('другое время без лица («поеду» → «поехал») — допуск DY4 как был', () => {
    const answer = 'Ты пишешь: «завтра снова поехал в центр и посмотрю расписание групп».';
    expect(unquoteAbsent(answer, MATERIALS).stripped).toHaveLength(0);
  });

  it('ревью 0.11.5: падеж существительного или прилагательного — не лицо, кавычки остаются', () => {
    const mat = [
      'Я ждала минут двадцать и потом пошла домой пешком.',
      'Доволен своим решением и хорошим началом недели.',
      'Пишу учителю о последнем уроке музыки.',
    ].join('\n');
    for (const q of [
      'ждала минуту двадцать и потом пошла домой пешком',
      'доволен своим решению и хорошим началом недели',
      'пишу учителем о последнем уроке музыки',
    ]) {
      expect(unquoteAbsent(`Ты пишешь: «${q}».`, mat).stripped, q).toHaveLength(0);
    }
  });
});

