// AG-1/AG-2 (12.11): счётчики опоры ответа в строке [chat-end] — только числа.
// Случай владельца: выдумка со ссылкой на настоящую заметку и дата не по шапке.
// Мутации: порог 0.3 → 0 → красный «выдумка»; без проверки шапки → красный «дата».
import { describe, it, expect } from 'vitest';
import { auditAnswer } from '../answerAudit';

const DOC = '[Хроника по вопросу]\n'
  + '[#n6 · 2026-11-06] «Одиночество»: дословно: Даша написала первой, пока я делал дыхательную практику, а потом подпропала.\n'
  + '[#n9 · 2026-11-09] «Аудио»: дословно: выпил около полулитра вина, спал поверхностно, воскресенье выпало из жизни.';

describe('счётчики опоры ответа', () => {
  it('выдумка со ссылкой и дата не по шапке — считаются', () => {
    const answer = '10 ноября ты заключил минимальный контракт: годовой отказ от сериалов, видеоигр и прочих развлечений [#n6]. '
      + 'В субботу ты выпил около полулитра вина и воскресенье выпало из жизни [#n9].';
    const a = auditAnswer(answer, DOC)!;
    expect(a.weak_ref).toBe(1);
    expect(a.date_off_header).toBe(1);
  });

  it('честный пересказ и дата шапки — ноль', () => {
    const answer = '6 ноября Даша написала первой, пока ты делал дыхательную практику [#n6]. '
      + '9 ноября: около полулитра вина, поверхностный сон [#n9].';
    const a = auditAnswer(answer, DOC)!;
    expect(a.weak_ref).toBe(0);
    expect(a.date_off_header).toBe(0);
  });
});
