// R7F-017: перенос пунктуации теряет границу предложения ровно на том слове,
// которое модель «поправила». Знак стоит после слова МОДЕЛИ («друзьями!»), у
// слова исходника («друзей») пары нет, и раньше ему выдавался простой пробел —
// человек получал «…из старых друзей Мы долго…». Слова при этом не менялись,
// гарантия держится и здесь.
import { describe, it, expect } from 'vitest';
import { transferPunctuation } from '../transferPunctuation';
import { sameWords } from '../sameWords';

describe('R7F-017: граница предложения на «исправленном» моделью слове', () => {
  it('восклицание после подменённого слова не теряется', () => {
    const raw = 'встретил старых друзей мы долго разговаривали';
    const model = 'Встретил старых друзьями! Мы долго разговаривали.';

    const r = transferPunctuation(raw, model)!;
    expect(r.text, 'знак обязан переехать на слово исходника, а не исчезнуть').toBe(
      'Встретил старых друзей! Мы долго разговаривали.',
    );
    expect(sameWords(raw, r.text), 'слова исходника не изменились').toBe(true);
  });

  it('точка после подменённого слова не превращает следующее предложение в продолжение', () => {
    const raw = 'кошка спит потом встанет';
    const model = 'Кошка отдыхает. Потом встанет.';

    const r = transferPunctuation(raw, model)!;
    expect(r.text).toBe('Кошка спит. Потом встанет.');
    expect(sameWords(raw, r.text)).toBe(true);
  });

  it('между двумя абзацами модели переносится разрыв, а не склейка', () => {
    const raw = 'первый абзац второй абзац';
    const model = 'Первый блок.\n\nВторой абзац.';

    const r = transferPunctuation(raw, model)!;
    expect(r.text).toBe('Первый абзац.\n\nВторой абзац.');
    expect(sameWords(raw, r.text)).toBe(true);
  });

  it('если следующее слово тоже без пары, чужой знак не берётся', () => {
    const raw = 'друзей мы';
    const model = 'Друзьями! Нас.';

    const r = transferPunctuation(raw, model)!;
    expect(r.coverage).toBe(0);
    // Начало фразы всегда с заглавной — это правило самого переноса, не знак модели.
    expect(r.text).toBe('Друзей мы');
    expect(sameWords(raw, r.text)).toBe(true);
  });

  // Ревью приёмки 0.10.0: модель выбросила слово-паразит («ну»). Слот перед
  // следующим совпавшим словом — это пара ПРЕДЫДУЩЕГО слова, его знак уже
  // поставлен; взять его второй раз — «ну, как» и «Ну. Мы».
  it('выброшенное моделью слово не удваивает знак соседа', () => {
    expect(transferPunctuation('привет ну как дела', 'Привет, как дела?')!.text).toBe('Привет, ну как дела?');
    // Регистр «Мы» — решение модели, здесь проверяется только знак.
    expect(transferPunctuation('встретил старых друзей ну мы долго', 'Встретил старых друзей. Мы долго.')!.text)
      .not.toMatch(/[Нн]у[.,]/);
  });

  it('пустой ответ модели — исходник без изменений', () => {
    const raw = 'просто текст без пунктуации';
    expect(transferPunctuation(raw, '')?.text).toBe('Просто текст без пунктуации');
  });
});
