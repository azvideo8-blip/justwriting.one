const TAILS = ['H1', 'H2', 'H3', 'H5'] as const;
const expectedWeak: Record<(typeof TAILS)[number], boolean> = { H1: true, H2: false, H3: true, H5: false };

describe('replyTail: чем кончился ответ собеседника', () => {
  it.each([
    ['H1', 'verify'], ['H2', 'proposal'], ['H3', 'none'], ['H5', 'open'], ['H6', 'open'],
  ] as const)('%s → %s', (id, tail) => { expect(replyTail(REPLIES[id])).toBe(tail); });
});

describe('confirmationOf: таблица «реплика × ответ собеседника»', () => {
  const byClass = (cls: string) => USER_REPLIES.filter(r => r.cls === cls);

  it('C (согласие словом) и M («запомни») — не null на всех четырёх ответах', () => {
    for (const r of [...byClass('C'), ...byClass('M')]) {
      for (const t of TAILS) {
        expect(confirmationOf(r.text, REPLIES[t]), `${r.id} «${r.text}» после ${t}`).not.toBeNull();
      }
    }
  });

  it('C_bare (голое «да») — weak после H1 и H3, null после H2 и H5', () => {
    for (const r of byClass('C_bare')) {
      for (const t of TAILS) {
        expect(confirmationOf(r.text, REPLIES[t]), `${r.id} «${r.text}» после ${t}`).toBe(expectedWeak[t] ? 'weak' : null);
      }
    }
  });

  it('H, YB, N, S, A, Q, P, T — null везде', () => {
    for (const cls of ['H', 'YB', 'N', 'S', 'A', 'Q', 'P', 'T', 'A_amb']) {
      for (const r of byClass(cls)) {
        for (const t of TAILS) {
          expect(confirmationOf(r.text, REPLIES[t]), `${cls} ${r.id} «${r.text}» после ${t}`).toBeNull();
        }
      }
    }
  });

  it('C_own (согласие своими словами) — null: известный пропуск, закрывает кнопка (DI-5)', () => {
    for (const r of byClass('C_own')) {
      for (const t of TAILS) expect(confirmationOf(r.text, REPLIES[t])).toBeNull();
    }
  });

  it('PART (согласие с частью) — сомнительное остаётся «нет» (настроено на точность; кнопка DI-5 закрывает)', () => {
    // Поведение прототипа, закреплено как есть: согласие должно открывать фразу.
    for (const r of [...byClass('PART'), ...byClass('PART_MOM'), ...byClass('PART_FIRST')]) {
      for (const t of TAILS) expect(confirmationOf(r.text, REPLIES[t]), `${r.id} «${r.text}» после ${t}`).toBeNull();
    }
  });

  it('пустая реплика и смайлик-согласие', () => {
    expect(confirmationOf('   ', REPLIES.H1)).toBeNull();
    expect(confirmationOf('👍', REPLIES.H2)).toBe('strong');
  });
});

describe('codeConclusion', () => {
  it('H1: фраза после «Если коротко:» без вопроса «Похоже на тебя?»', () => {
    const c = codeConclusion(REPLIES.H1);
    expect(c).not.toBeNull();
    expect(c).toContain('своё и приятное у тебя идёт только после того, как всё остальное сделано');
    expect(c).not.toContain('Похоже на тебя');
  });

  it('H6 (одни вопросы): null', () => {
    expect(codeConclusion(REPLIES.H6)).toBeNull();
  });
});
