// DL-19 (19.3): склейка через границу фразы кавычки теряет. Фикстуры — синтетическая
// расшифровка (выдуманные Вера и Ирина Львовна), ни строки из живого архива.
// Мутации: вернуть `hay.includes(...)` и `bestInOrder(qWords, hayWords, …)` —
// краснеют «склейка» и «склейка внутри одной реплики»; снять окно внутри фразы в
// «почти дословной» — краснеет «одно слово мимо внутри одной фразы» на материалах,
// где эти слова стоят в разных фразах.
import { describe, expect, it } from 'vitest';
import { countAbsentQuotes, unquoteAbsent } from '../quoteGuard';

const MATERIALS = [
  '[#local_dl19_note · 20261018]',
  '[Прикрепленная заметка]',
  'Вера: Я всю неделю не могла уснуть после концерта и не знаю почему.',
  'Ирина Львовна: А если не спать — это про что-то другое?',
  '',
  'Вера: Он поставил ноутбук на стол и сказал — поезжай один.',
  'Я ему ответила, что посмотрю по репетициям.',
  'А потом полтора часа сидела с остывшим чаем.',
].join('\n');

describe('DL-19 19.3: склейка двух соседних фраз', () => {
  it('через границу реплик — кавычки сняты, слова остались', () => {
    const answer = 'Ты пишешь: «я всю неделю не могла уснуть после концерта и не знаю почему. А если не спать — это про что-то другое?».';
    const out = unquoteAbsent(answer, MATERIALS);
    expect(out.stripped).toHaveLength(1);
    expect(out.text).not.toContain('«я всю неделю');
    expect(out.text).toContain('и не знаю почему. А если не спать — это про что-то другое?');
  });

  // DY5 (разбор DL-19): дословная цитата из двух фраз одной реплики, где граница
  // стоит там же, — это слова человека, кавычки остаются (урок R-1; на ra1-full
  // таких 14). Мутация: сравнивать по одной фразе (`phrases.some`) → красный.
  it('две фразы подряд одной реплики с той же границей — кавычки остаются', () => {
    const answer = 'Ты рассказываешь: «он поставил ноутбук на стол и сказал — поезжай один. Я ему ответила, что посмотрю по репетициям».';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });

  // Граница съедена — две фразы поданы одной. Мутация: сравнивать по всему
  // свёрнутому тексту без границ → красный.
  it('склейка, где точка между фразами стала тире, — кавычки сняты', () => {
    const answer = 'Ты рассказываешь: «он поставил ноутбук на стол и сказал — поезжай один — я ему ответила, что посмотрю по репетициям».';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(1);
  });

  it('дословная цитата внутри одной фразы — кавычки остаются', () => {
    expect(countAbsentQuotes('Ты пишешь «я всю неделю не могла уснуть после концерта и не знаю почему».', MATERIALS)).toBe(0);
  });

  it('одно выпавшее слово внутри одной фразы — кавычки остаются (15.1б)', () => {
    expect(countAbsentQuotes('Ты пишешь «всю неделю не могла уснуть и не знаю почему».', MATERIALS)).toBe(0);
  });

  it('то же самое слово мимо, но фразы в материалах разные — кавычки сняты', () => {
    // «не спать» — из реплики Ирины Львовны, остальное — из реплики Веры: до 19.3
    // страж видел это подряд по всему тексту и оставлял кавычки.
    expect(countAbsentQuotes('Ты пишешь «всю неделю не могла уснуть после концерта не спать это про что-то другое».', MATERIALS)).toBe(1);
  });

  it('без материалов правило молчит', () => {
    expect(unquoteAbsent('Ты пишешь: «одна фраза. И вторая сразу за ней».', '').stripped).toEqual([]);
  });
});

// DY5-2 (дейлик 2026-10-25): страж зовётся на каждый чанк потока по всему ответу.
// 0.10.10 сверял каждую цитату заново на каждом чанке. Порог в миллисекундах и
// отношение сумм за прогон мигали под полным vitest; медиана по блокам — ~4×
// под нагрузкой, без кэша вердиктов 1,5×, без кэша фраз 1×.
// Мутации: убрать кэш вердиктов (`cached` → `f()`) или кэш фраз → красный.
describe('DY5-2: стоимость стража на потоке', () => {
  it('чанки с кэшем как минимум вдвое дешевле, чем без него (медиана по блокам)', () => {
    const vocab = 'вечер лампа утро чай окно дорога письмо голос шаг рука дверь свет тень поезд город'.split(' ');
    const sentence = (i: number) => `${Array.from({ length: 9 }, (_, k) => vocab[(i * 7 + k * 3) % vocab.length]).join(' ')}.`;
    const materials = Array.from({ length: 1000 }, (_, i) => sentence(i)).join(' ');
    const quote = Array.from({ length: 30 }, (_, k) => vocab[(k * 5 + 1) % vocab.length]).join(' ');
    const answer = `Итог: ${'обычный текст ответа. '.repeat(40)} ты пишешь «${quote}» и дальше. А ещё «${quote.split(' ').slice(0, 12).join(' ')}» тут.`;
    // Блоками по 10 чанков: 10 без кэша (каждый раз новая строка материалов), затем
    // 10 с кэшем (одна строка; первый вызов блока кэш строит заново — память на
    // одну запись). Медиана отношения по блокам: всплеск нагрузки портит блок, а
    // не итог (сумма за прогон мигала под полным vitest).
    const time = (f: () => void) => { const t0 = performance.now(); f(); return performance.now() - t0; };
    const ratios: number[] = [];
    for (let b = 0; b < 8; b++) {
      let cold = 0, warm = 0;
      for (let c = 0; c < 10; c++) cold += time(() => unquoteAbsent(answer + ' ещё'.repeat(c), `${materials}${' '.repeat(b * 10 + c + 1)}`));
      for (let c = 0; c < 10; c++) warm += time(() => unquoteAbsent(answer + ' ещё'.repeat(c), materials));
      ratios.push(cold / warm);
    }
    const median = ratios.sort((x, y) => x - y)[4]!;
    expect(median, `без кэша / с кэшем по блокам: ${ratios.map(r => r.toFixed(1)).join(', ')}`).toBeGreaterThan(2);
  });
});
