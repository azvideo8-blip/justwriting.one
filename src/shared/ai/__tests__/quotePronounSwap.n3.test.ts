// Дейлик 28.11 (Н-3): «почти дословная» цитата с подменой лица или объекта
// («его» → «её») оставалась в кавычках как слова человека. Синтетика.
// Мутация: снять pronounSwapped из допуска — красный.
import { describe, it, expect } from 'vitest';
import { unquoteAbsent } from '../quoteGuard';

const MAT = 'Я не хочу его видеть вечером, потому что устала. Мама звонила дважды.';

describe('Н-3: подмена местоимения — не огреха', () => {
  it('«его» → «её» — кавычки сняты', () => {
    const A = 'Про вечер она написала: «я не хочу её видеть вечером, потому что устала».';
    expect(unquoteAbsent(A, MAT).stripped.length).toBe(1);
  });

  it('контроль: дословная цитата живёт', () => {
    const A = 'Про вечер она написала: «я не хочу его видеть вечером, потому что устала».';
    expect(unquoteAbsent(A, MAT).stripped.length).toBe(0);
  });

  it('контроль: огреха в обычном слове (одно слово мимо) — кавычки остаются', () => {
    const A = 'Про вечер она написала: «я не хочу его видеть сегодня вечером, потому что устала».';
    expect(unquoteAbsent(A, MAT).stripped.length).toBe(0);
  });
});
