// Дейлик 28.11 (Н-2): «выброс выдуманного предложения» резал текст только по знакам
// конца предложения — выдумка в заголовке или жирной подводке (без точки) уносила с
// собой следующую строку, взятую из записи дословно. Синтетика.
// Мутация: вернуть прежнее разбиение без переноса строки — красный.
import { describe, it, expect } from 'vitest';
import { dropFabricatedSentences } from '../quoteGuard';

const MAT = 'Мама устала. Сестра приехала поздно и сразу легла спать.';

describe('Н-2: выдумка в заголовке не уносит соседнюю строку', () => {
  it('жирная подводка с выдумкой — уходит только она', () => {
    const A = '**Про «мы все виноваты в этом вечере»\n\nСестра приехала поздно и сразу легла спать. Так было.**';
    const out = dropFabricatedSentences(A, MAT);
    expect(out).not.toContain('виноваты');
    expect(out).toContain('Сестра приехала поздно и сразу легла спать');
  });

  it('заголовок markdown с выдумкой — следующий абзац цел', () => {
    const A = '### «Я никогда никого не прощаю»\nСестра приехала поздно и сразу легла спать.';
    const out = dropFabricatedSentences(A, MAT);
    expect(out).not.toContain('никогда никого');
    expect(out).toContain('Сестра приехала поздно');
  });

  it('контроль: выдумка в обычном предложении — соседние предложения целы', () => {
    const A = 'Ты писала: «мы все виноваты в этом вечере». Сестра приехала поздно и сразу легла спать.';
    const out = dropFabricatedSentences(A, MAT);
    expect(out).not.toContain('виноваты');
    expect(out).toContain('Сестра приехала поздно');
  });
});
