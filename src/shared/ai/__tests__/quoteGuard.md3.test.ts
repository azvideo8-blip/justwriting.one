// MD-3 (0.9.38): кавычка только для дословного. Фикстуры синтетические —
// выдуманная авторка и выдуманные люди, ни строки из живого архива.
import { describe, expect, it } from 'vitest';
import { countAbsentQuotes, normalizeQuoteText, unquoteAbsent } from '../quoteGuard';

const MATERIALS = [
  '[Сегодня: воскресенье, 11 октября 2026]',
  '',
  '[#local_v102 · 20261009]',
  '[Прикрепленная заметка]',
  'Вечером Соня сказала: «Я не хочу, чтобы она возненавидела музыку из-за меня».',
  'А потом добавила тихо — это держится на честном слове.',
  '',
  '[#local_k07 · 20260928] Строки фона: за три дня до этой записи взяли скрипку напрокат.',
  '',
  'Результаты поиска по архиву заметок (запрос: "скрипка"). Найдено заметок: 1 (отобрано 1).',
  '',
  '[#local_k08 · 20260915]',
  'Заметка 1: "Прокат"',
  'Взяли инструмент напрокат.',
  '',
  'Реплика человека: я ей сказала «держись, разберёмся в четверг» и ушла.',
].join('\n');

describe('MD-3: дословная цитата выживает', () => {
  it('другие кавычки, другой регистр и перенос строки внутри', () => {
    const answer = 'Соня ответила “я не хочу, чтобы она\nвозненавидела музыку из-за меня”.';
    expect(unquoteAbsent(answer, MATERIALS)).toEqual({ text: answer, stripped: [] });
  });

  it('цитата из строки фона — она в материалах хода', () => {
    const answer = 'Позже: «взяли скрипку напрокат», и это отдельный день.';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });

  it('свои слова человека из этого диалога остаются в кавычках', () => {
    const answer = 'Ты ей написала: «держись, разберёмся в четверг».';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });

  it('пунктуация и ё при сверке не решают', () => {
    const answer = 'Реплика: «Я не хочу, чтобы она — возненавидела музыку из-за меня!»';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });
});

describe('MD-3: чего в материалах нет — теряет кавычки', () => {
  it('пересказ в кавычках: слова остаются, кавычки снимаются', () => {
    const out = unquoteAbsent('Соня переживает, «она боится сорваться на дочку».', MATERIALS);
    expect(out.text).toBe('Соня переживает, она боится сорваться на дочку.');
    expect(out.stripped).toEqual(['она боится сорваться на дочку']);
  });

  it('гипотеза модели в кавычках тоже снимается (S5 считает её недословной)', () => {
    expect(countAbsentQuotes('Может быть, внутри звучит «я подменила заботу контролем».', MATERIALS)).toBe(1);
  });

  it('прямые и фигурные кавычки обрабатываются одинаково', () => {
    expect(unquoteAbsent('Сказала "я справлюсь сама, не надо помогать".', MATERIALS).text)
      .toBe('Сказала я справлюсь сама, не надо помогать.');
  });

  it('вложенные кавычки: внешние снимаются, внутренние остаются', () => {
    const out = unquoteAbsent('Мама сказала: «Соня шепнула „не хочу на этот конкурс“ и замолчала».', MATERIALS);
    expect(out.stripped).toEqual(['Соня шепнула „не хочу на этот конкурс“ и замолчала']);
    expect(out.text).toBe('Мама сказала: Соня шепнула „не хочу на этот конкурс“ и замолчала.');
  });

  it('без материалов правило молчит', () => {
    const answer = 'Она сказала «ничего не помню про тот четверг».';
    expect(unquoteAbsent(answer, '')).toEqual({ text: answer, stripped: [] });
    expect(unquoteAbsent(answer, null)).toEqual({ text: answer, stripped: [] });
  });

  it('несколько цитат считаются все', () => {
    const answer = '«первая чужая реплика дня», «и вторая не из заметки», «третья вовсе тут выдумана».';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(3);
  });
});

describe('MD-3: короткие кавычки не трогаются', () => {
  it('три слова — метка, а не речь', () => {
    const answer = 'Это «может быть, потом» и «на честном слове».';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });

  it('термин в прямых кавычках остаётся', () => {
    const answer = 'Разговор про "тихий метроном".';
    expect(countAbsentQuotes(answer, MATERIALS)).toBe(0);
  });
});

// Находки 10.6 / 11.3: двухсловная «цитата», поданная как слова человека, которой
// в материалах нет, проходила — порог был от четырёх слов для любых кавычек.
// Мутация: убрать ветку глагола речи → первый тест красный.
describe('короткая цитата, поданная как слова человека', () => {
  it('нет в материалах → кавычки снимаются', () => {
    const { text, stripped } = unquoteAbsent('Ты пишешь «сама виновата», и это звучит жёстко.', MATERIALS);
    expect(stripped).toEqual(['сама виновата']);
    expect(text).toBe('Ты пишешь сама виновата, и это звучит жёстко.');
  });

  it('есть в материалах → кавычки остаются', () => {
    expect(countAbsentQuotes('Ты называешь это «честном слове».', MATERIALS)).toBe(0);
  });

  it('без глагола речи короткий термин не трогается', () => {
    expect(countAbsentQuotes('Похоже на «слепое пятно».', MATERIALS)).toBe(0);
  });
});

describe('MD-3: нормализка', () => {
  it('свертывает регистр, ё, кавычки любых видов и пунктуацию', () => {
    expect(normalizeQuoteText('«Ёлка, ЁЖ — не „зверь“!»')).toBe('елка еж не зверь');
  });
});
