// К26-2 (случай #26): снятая цитата посреди фразы без знака перед ней ломала
// фразу. Ставится двоеточие; после знака, в начале фразы и с глаголом речи — как раньше.
import { describe, expect, it } from 'vitest';
import { unquoteAbsent } from '../quoteGuard';

const MATERIALS = 'Вечером опять полчаса листала чат команды. Потом не могла уснуть.';

describe('К26-2: снятая цитата держит границу фразы', () => {
  it('посреди фразы без знака — двоеточие', () => {
    expect(unquoteAbsent('Можно спросить себя «а что будет, если не отвечу до утра» и посмотреть.', MATERIALS, { markPersonal: false }).text)
      .toBe('Можно спросить себя: а что будет, если не отвечу до утра и посмотреть.');
  });
  it('после двоеточия или тире — без второго знака', () => {
    expect(unquoteAbsent('Вопрос простой: «а что будет, если не отвечу до утра».', MATERIALS, { markPersonal: false }).text)
      .toBe('Вопрос простой: а что будет, если не отвечу до утра.');
    expect(unquoteAbsent('Вопрос простой — «а что будет, если не отвечу до утра».', MATERIALS, { markPersonal: false }).text)
      .toBe('Вопрос простой — а что будет, если не отвечу до утра.');
  });
  it('в начале фразы — без знака', () => {
    expect(unquoteAbsent('Понимаю. «А что будет, если не отвечу до утра» — вот вопрос.', MATERIALS, { markPersonal: false }).text)
      .toBe('Понимаю. А что будет, если не отвечу до утра — вот вопрос.');
  });
  it('после предлога, союза, «не» — без двоеточия: «и: значит», «рядом с: жду» ломали фразу', () => {
    expect(unquoteAbsent('Между «может быть, это одобрение» и «значит, я жду одобрения» почти нет зазора.', MATERIALS, { markPersonal: false }).text)
      .toBe('Между может быть, это одобрение и значит, я жду одобрения почти нет зазора.');
    expect(unquoteAbsent('Это уже не «собрать всё и сразу правильно», а очередь.', MATERIALS, { markPersonal: false }).text)
      .toBe('Это уже не собрать всё и сразу правильно, а очередь.');
  });
  it('глагол речи и «не» перед цитатой — без «, по смыслу:» посреди («сказал не, по смыслу: …»)', () => {
    expect(unquoteAbsent('Ты впервые сказал не «чего мне не хватает сейчас», а «куда я хочу идти».', MATERIALS, { markPersonal: false }).text)
      .toBe('Ты впервые сказал не чего мне не хватает сейчас, а куда я хочу идти.');
  });
  it('вопрос в снятых кавычках перед точкой — без «?.»', () => {
    expect(unquoteAbsent('Спроси себя: «сделал бы я это, если бы никто не видел?».', MATERIALS, { markPersonal: false }).text)
      .toBe('Спроси себя: сделал бы я это, если бы никто не видел?');
  });
  it('дословная цитата из записи — кавычки на месте', () => {
    const t = 'Ты пишешь «опять полчаса листала чат команды» — и это повторяется.';
    expect(unquoteAbsent(t, MATERIALS).text).toBe(t);
  });
});
