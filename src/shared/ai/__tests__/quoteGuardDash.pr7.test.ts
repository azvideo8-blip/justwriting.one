// PR-7 (17.8): перед меткой срезались пробел, двоеточие и запятая, но не тире:
// «звучит так — «…»» превращалось в «звучит так —, по смыслу:». После тире
// метка идёт без запятой.
//
// Мутация: убрать ветку тире → красные оба.
import { describe, it, expect } from 'vitest';
import { unquoteAbsent } from '../quoteGuard';

const MATERIALS = 'Соня пишет про музыку и конкурс, про то, как она устала.';

describe('PR-7: «по смыслу» после тире', () => {
  it('тире перед цитатой — без запятой', () => {
    // Пересказ, а не дословная: четыре слова из шести идут по порядку, «так» мимо.
    expect(unquoteAbsent('Звучит так — «я больше не могу так жить».', 'Соня пишет про музыку. Я больше не умею жить, и это важно.').text)
      .toBe('Звучит так — по смыслу: я больше не могу так жить.');
  });

  it('тире после глагола речи — тоже без запятой', () => {
    expect(unquoteAbsent('Она сказала — «буду говорить только по делу».', MATERIALS).text)
      .toBe('Она сказала — по смыслу: буду говорить только по делу.');
  });

  it('двоеточие и запятая остаются прежними', () => {
    expect(unquoteAbsent('Она ответила: «буду говорить только по делу».', MATERIALS).text)
      .toBe('Она ответила, по смыслу: буду говорить только по делу.');
    expect(unquoteAbsent('Она ответила, «буду говорить только по делу».', MATERIALS).text)
      .toBe('Она ответила, по смыслу: буду говорить только по делу.');
  });
});
