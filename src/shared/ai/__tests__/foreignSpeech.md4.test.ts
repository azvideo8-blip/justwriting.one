// MD-4 (0.9.38): детектор чужой прямой речи и плашка «остались чужие слова».
// Имена и тексты выдуманы; форма та же, что у трёх заметок S6 стенда (родитель
// ученицы, мальчик из третьего класса, ученица), но строки — свои.
import { describe, expect, it } from 'vitest';
import { foreignSpeechQuotes, postKeepsForeignWords } from '../foreignSpeech';

const NOTE = [
  'Вторник, конец дня.',
  '',
  'Галина попросила остаться после урока и сказала: «Я боюсь, что Петька бросит скрипку, как я в четырнадцать». Потом добавила: «Я давлю на него, потому что боюсь».',
  '',
  'Я ответила, что он играет с удовольствием. Это правда.',
  '',
  'А вечером думала про себя: отец тоже ставил метроном и выходил из комнаты, и я играла, потому что боялась тишины.',
].join('\n');

describe('MD-4: чужая прямая речь', () => {
  it('реплики другого человека найдены обе', () => {
    expect(foreignSpeechQuotes(NOTE)).toEqual([
      'Я боюсь, что Петька бросит скрипку, как я в четырнадцать',
      'Я давлю на него, потому что боюсь',
    ]);
  });

  it('«Я сказала: „…"» — речь автора, не чужая', () => {
    expect(foreignSpeechQuotes('Я сказала Петьке: «Приходи в четверг, разберём трудное место».')).toEqual([]);
  });

  it('подлежащее пропущено, но впереди «я» — это автор', () => {
    const text = 'Я не знала, что ответить, и ответила как учитель: «Тогда давай играть так громко, как тебе нужно».';
    expect(foreignSpeechQuotes(text)).toEqual([]);
  });

  it('подлежащее пропущено, впереди «она» — это другой человек', () => {
    const text = 'Она повернулась к окну. Сказала: «Мне нужно подумать до среды».';
    expect(foreignSpeechQuotes(text)).toEqual(['Мне нужно подумать до среды']);
  });

  it('обратный порядок: «„Давай“, — сказала она»', () => {
    expect(foreignSpeechQuotes('«Ты справишься, я в тебя верю», — сказала она.')).toEqual(['Ты справишься, я в тебя верю']);
    expect(foreignSpeechQuotes('«Ты справишься, я в тебя верю», — сказала я.')).toEqual([]);
  });

  it('короткие кавычки — метки, а не реплики', () => {
    expect(foreignSpeechQuotes('Мама сказала: «Потерпи чуть-чуть», и ушла.')).toEqual([]);
    expect(foreignSpeechQuotes('Тренер крикнул: «Ещё раз»')).toEqual([]);
  });

  it('косвенная речь без кавычек не считается', () => {
    expect(foreignSpeechQuotes('Она сказала, что в детстве её саму заставляли играть и бросила в четырнадцать.')).toEqual([]);
  });
});

describe('MD-4: чужие слова в посте', () => {
  it('фрагмент чужой реплики из четырёх слов найден', () => {
    const post = 'Иногда родитель приходит и говорит, что боюсь, что Петька бросит скрипку. И всё.';
    expect(postKeepsForeignWords(post, NOTE)).toBe(true);
  });

  it('пересказ своими словами — не попадание', () => {
    const post = 'Родительница боится, что ребёнок забросит занятия, и давит сильнее, чем хочет.';
    expect(postKeepsForeignWords(post, NOTE)).toBe(false);
  });

  it('регистр и пунктуация не решают', () => {
    const post = 'ЕЁ СЛОВА: «Я давлю на него!», а ответ один.';
    expect(postKeepsForeignWords(post, NOTE)).toBe(true);
  });

  it('собственная фраза автора в посте не попадает', () => {
    const post = 'Я ответила, что он играет с удовольствием. Это правда.';
    expect(postKeepsForeignWords(post, NOTE)).toBe(false);
  });
});
