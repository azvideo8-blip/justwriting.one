import { describe, expect, it } from 'vitest';
import { countMisspelledQuotes } from '../quoteGuard';
import { auditAnswer } from '../answerAudit';

// К29-5: слово автора в кавычках с другой буквой — только счёт.
// Мутации: длина не сверяется; окончание не исключается; порог слов снят; слово
// из материалов считается — красный.
const M = 'Сегодня чувствую опустошённость и растерянность после разговора о переезде. Дом пуст.';

describe('К29-5: искажённое слово автора в короткой цитате', () => {
  it.each([
    ['одна буква внутри слова', 'Ты пишешь про «опустошонность».', 1],
    ['в паре слов', 'Твоё «чувствую опустошонность» важно.', 1],
    ['прямые кавычки', 'Слово "растиранность" и "ростерянность".', 1],
    ['верное слово', 'Твоя «опустошённость» и «растерянность».', 0],
    ['другой падеж', 'Вокруг «опустошённости» и «переезду».', 0],
    ['другое слово', 'Это «усталость» и «пустота».', 0],
    ['буква и длина', 'Это «опустошонност».', 0],
    ['короткое слово', 'Это «пист».', 0],
    ['длинная цитата — дело стража', 'Ты пишешь «сегодня чувствую опустошонность и растерянность».', 0],
    ['без кавычек', 'Ты пишешь про опустошонность.', 0],
  ])('%s', (_n, text, want) => {
    expect(countMisspelledQuotes(text, M)).toBe(want);
  });

  it('без материалов — ноль; в строке журнала — число', () => {
    expect(countMisspelledQuotes('«опустошонность»', '')).toBe(0);
    expect(auditAnswer('Ты пишешь про «опустошонность».', M)!.quote_misspelled).toBe(1);
  });
});
