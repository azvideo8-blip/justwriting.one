// К23-2 (шаг 1), К23-5, К23-6 (случай #23): счётчики формы ответа в [chat-end] —
// только числа. Фикстуры синтетические.
// Мутации: в questionRun не идти по прошлым ответам → красный «серия»;
// CHOICE_EXIT_RE не проверять → красный «выход»; HEADER_RE без дефисов в дате →
// красный «приложенная заметка».
import { describe, it, expect } from 'vitest';
import { auditAnswer } from '../answerAudit';
import { formatRefTag } from '../../../features/ai/utils/attachedNoteFormat';

const DOC = '[#n1 · 2026-11-01] «Утро»: дословно: проснулся рано, долго смотрел в окно.';

describe('К23-2: серия ответов, кончающихся вопросом', () => {
  it('считает подряд с конца, включая этот ответ', () => {
    const prior = ['Что тогда было?', 'Понятно. Это важно.', 'А как ты это понял?', 'И что дальше?'];
    expect(auditAnswer('Похоже на усталость. Когда это началось?', DOC, null, prior)!.question_run).toBe(3);
  });
  it('вопрос, за которым ссылка, — тоже вопрос (ревью 0.11.13)', () => {
    expect(auditAnswer('Это было про отдых? [#n1]', DOC, null, ['И что дальше? [#n1].'])!.question_run).toBe(2);
  });
  it('ответ без вопроса в конце — ноль', () => {
    expect(auditAnswer('Похоже на усталость.', DOC, null, ['Что тогда было?'])!.question_run).toBe(0);
  });
  it('первый ответ диалога с вопросом — один', () => {
    expect(auditAnswer('Когда это началось?', DOC)!.question_run).toBe(1);
  });
});

describe('К23-5: вопрос-выбор без выхода в конце ответа', () => {
  it('«A или B?» — 1', () => {
    expect(auditAnswer('Ты описал утро. Это было про отдых или про бегство?', DOC)!.either_or_end).toBe(1);
  });
  it.each([
    'Это было про отдых или про что-то другое?',
    'Это было про отдых, про бегство — или иначе?',
    'Это было про отдых? Или про бегство, а может, ни про то, ни про другое?',
    'Что для тебя было в этом утре?',
  ])('«%s» — 0', (answer) => {
    expect(auditAnswer(answer, DOC)!.either_or_end).toBe(0);
  });
  it('выбор не в последнем вопросе — 0', () => {
    expect(auditAnswer('Отдых или бегство? Что ты сам об этом думаешь?', DOC)!.either_or_end).toBe(0);
  });
});

describe('К23-6: ссылка на приложенную заметку тоже в счётчике опоры (AG-1)', () => {
  it('вывод модели под ссылкой на приложенную заметку считается', () => {
    const doc = formatRefTag({
      documentId: 'local_k236', title: 'Утро', lastSessionAt: Date.UTC(2026, 10, 1, 9),
      content: 'Проснулся рано, долго смотрел в окно, потом пошёл гулять с собакой.',
    });
    const weak = 'Ты боишься перемен и поэтому откладываешь важные разговоры с близкими [#local_k236].';
    const grounded = 'Ты проснулся рано и долго смотрел в окно, потом гулял с собакой [#local_k236].';
    expect(auditAnswer(weak, doc)!.weak_ref).toBe(1);
    expect(auditAnswer(grounded, doc)!.weak_ref).toBe(0);
  });
});
