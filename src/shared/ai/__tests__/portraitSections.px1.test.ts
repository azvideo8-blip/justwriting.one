// PX-1: что остаётся от портрета в строгом ходе разбора приложенной заметки.
// Кейс 9.9: генератор пишет «Стиль общения» не тремя предложениями, а на
// несколько экранов, с подзаголовками и списком ключевых тем — темы поэтому
// доезжали до строгого хода. Кейс 9.8: при старом формате (раздела нет) в ход
// уходил весь портрет. Данные только синтетические (выдуманная авторка —
// инженер, не скрипачка стенда).
import { describe, expect, it } from 'vitest';
import { strictTurnPortrait } from '../portraitSections';

const CLEAN = `# Психологический портрет пользователя

## Темы и интересы
Две линии: работа на заводе и длинные пешие маршруты.

## Стиль общения
Обращение на «ты», о человеке — в женском роде. Любит точные слова и не любит,
когда её утешают. Ответы без списков, если она сама не попросила план.
`;

// Как реально выглядит вывод генератора: preamble без заголовка, затем блоки
// `### …` и жирной строкой `**…**`, среди них — список ключевых тем с именем и
// детским эпизодом.
const PRODSHAPE = `# Психологический портрет пользователя

## Темы и интересы
Инна возвращается к заводу и к разговору с братом Романом о материнской даче.

## Стиль общения

Обращение на «ты», о человеке — в женском роде. Сначала пересказ текста, потом
одна гипотеза с проверкой.

### Общий рисунок
Ждёт буквального пересказа; обобщения до факта раздражают. Любит точные слова:
«перекур», а не «отдых».

### Ключевые темы, к которым она возвращается
- Роман и материнская дача — молчание по три недели, вина за него.
- Цех и наряды на неделю — страх, что план сорвут.
- Метроном в детстве: отец уходил из комнаты, мать ждала за дверью.

### Предпочтения в общении
Спокойный тон без эмоциональной подложки. Не надо списков, если её не просили.
Полезно называть её словами то, что она уже сказала, и спрашивать «так?».

**Что для неё важно**
Довести смену до готовности важнее, чем получить благодарность.

**Возможные сложности**
Раздражает, когда чувство называют раньше факта из записи. Плохо переносит
вопрос «почему ты не попросила помощь» — считает его упрёком.

### Итог
Нужны буквальный пересказ, одна гипотеза и короткий вопрос.
`;

const THEME_MARKERS = ['Роман', 'роман', 'дача', 'метроном', 'наряды', 'Цех', 'отец', 'мать', 'выгорание'];

describe('PX-1: в строгий ход — только то, как говорить', () => {
  it('prodshape: остаются блоки про предпочтения и сложности, оба вида заголовков', () => {
    const out = strictTurnPortrait(PRODSHAPE)!;
    expect(out).toContain('### Предпочтения в общении');
    expect(out).toContain('Спокойный тон без эмоциональной подложки');
    expect(out).toContain('**Возможные сложности**');
    expect(out).toContain('Плохо переносит');
  });

  it('prodshape: тем, имён и детских эпизодов из списка ключевых тем не остаётся', () => {
    const out = strictTurnPortrait(PRODSHAPE)!;
    for (const marker of THEME_MARKERS) expect(out, marker).not.toContain(marker);
    expect(out).not.toContain('Ключевые темы');
    expect(out).not.toContain('Общий рисунок');
    expect(out).not.toContain('Что для неё важно');
    expect(out).not.toContain('Итог');
  });

  it('чистый раздел в 3 предложения остаётся как есть', () => {
    const out = strictTurnPortrait(CLEAN);
    expect(out).toBe('Обращение на «ты», о человеке — в женском роде. Любит точные слова и не любит,\nкогда её утешают. Ответы без списков, если она сама не попросила план.');
  });

  it('9.8: раздела «Стиль общения» нет — null, а не весь портрет', () => {
    const old = `# Психологический портрет пользователя\n\n## Темы и интересы\nРемонт и пешие маршруты.\n\n## Эмоциональные паттерны\nЗакрывается, когда разговор не складывается.\n`;
    expect(strictTurnPortrait(old)).toBeNull();
    expect(strictTurnPortrait(null)).toBeNull();
    expect(strictTurnPortrait('')).toBeNull();
  });

  it('простыня без подзаголовков (>800 знаков) — старый формат с темами, null', () => {
    const wall = `## Стиль общения\n${'Она любит точные слова и не любит утешений, а ещё возвращается мыслью к ремонту и к разговору с братом. '.repeat(15)}`;
    expect(wall.length).toBeGreaterThan(800);
    expect(strictTurnPortrait(wall)).toBeNull();
  });

  it('подзаголовки есть, но ни один не про то, как говорить — null', () => {
    const out = strictTurnPortrait('## Стиль общения\n### Ключевые темы\nРоман и дача.\n\n### Ценности\nДовести смену до конца.\n');
    expect(out).toBeNull();
  });

  it('заголовок с темой внутри не «тон» и не «предпочтения» — блок вне (граница слова)', () => {
    // «Стоимость», «картон» — не про тон общения
    const out = strictTurnPortrait('## Стиль общения\n### Стоимость ответа\nСчитает деньги.\n\n### Картон и бумага\nХранит черновики.\n\n### Предпочтения в общении\nКоротко и по делу.\n');
    expect(out).toBe('### Предпочтения в общении\nКоротко и по делу.');
  });
});

// Ревью 0.9.39: формы заголовков, которые первая версия не видела, — и через
// них темы снова доезжали до строгого хода. Мутации: убрать ветку «строка с
// двоеточием» и вернуть «:» в концы предложений → красный первый кейс; вернуть «тон» префиксом → красный третий;
// убрать KEPT_MAX → красный четвёртый.
describe('PX-1, ревью 0.9.39: темы не протекают через другие формы заголовков', () => {
  const wrap = (style: string) => `# Портрет\n\n## Темы и интересы\nЗавод и маршруты.\n\n## Стиль общения\n${style}\n`;

  it('«Ключевые темы:» строкой с двоеточием обрывает блок «как говорить»', () => {
    const out = strictTurnPortrait(wrap(`**Тон**
Спокойный, без восклицаний и без утешений, с одной гипотезой на ответ.
Ключевые темы:
- Роман и материнская дача, молчание по три недели.
- Метроном в детстве, отец уходил из комнаты.`));
    expect(out).toContain('Спокойный');
    expect(out).not.toMatch(/Роман|Метроном|дача/);
  });

  it('жирный пункт списка «- **Темы**» — тоже заголовок, и его блок не едет', () => {
    const out = strictTurnPortrait(wrap(`- **Предпочтения**
Сначала пересказ текста, потом одна гипотеза с проверкой «так?».
- **Темы**
Роман и материнская дача, цех и наряды на неделю, страх сорванного плана.`));
    expect(out).toContain('пересказ');
    expect(out).not.toMatch(/Роман|цех/);
  });

  it('«Тонкие места» — не про тон: блок не попадает в строгий ход', () => {
    const out = strictTurnPortrait(wrap(`**Предпочтения**
Сначала пересказ текста, потом одна гипотеза с проверкой «так?».
**Тонкие места**
Роман и материнская дача; отец, который уходил из комнаты, когда она играла.`));
    expect(out).toContain('пересказ');
    expect(out).not.toMatch(/Роман|отец/);
  });

  it('блок «как говорить» длиннее потолка — в строгий ход не едет ничего', () => {
    const long = 'Ценит конкретику и точные слова, не любит обобщений. '.repeat(30);
    expect(strictTurnPortrait(wrap(`**Предпочтения**\n${long}`))).toBeNull();
  });

  it('подзаголовок «### Стиль общения…» в другом разделе не считается разделом', () => {
    const portrait = `# Портрет\n\n## Темы и интересы\n### Стиль общения с братом\nРоман и дача — молчание по три недели, вина за него, долгие паузы.\n`;
    expect(strictTurnPortrait(portrait)).toBeNull();
  });
});
