/**
 * К21-4 (случай #21, 21.2): признак «ответ в ходе с выдачей пересказывает
 * записи, но не ссылается ни на одну». Правило одно и для сервера (счётчик в
 * строку `[chat-end]`), и для клиента (пометка под ответом): две реализации
 * разошлись бы на формах, и человек видел бы пометку там, где журнал её не
 * считает, или наоборот.
 *
 * Признак — не отсутствие ссылок само по себе: без выдачи ссылаться не на что
 * (правило ссылок в NOTES_GUARD_BASE велят говорить «по недавним записям» без
 * скобок), а в строгом ходу ссылкой была бы приложенная заметка. Считаем только
 * ход, где модель видела найденные записи, и только ответ, который на них
 * указывает словами.
 */

const fold = (s: string): string => s.toLowerCase().replace(/ё/g, 'е');

/**
 * Блок результатов поиска и его непустота. Пустой блок — «Найдено заметок: 0»
 * или блок вовсе без шапок «Заметка N: "…"» — это законное «ничего не нашлось»:
 * ссылаться не на что, и провалом он не считается.
 */
export const RESULTS_HEAD_RE = /Результаты поиска по архиву заметок/;
export const RESULTS_FOUND_RE = /Найдено заметок: [1-9]\d*|Заметка \d+:\s*"/;

/**
 * Ссылка ответа: `[#id]`, `[#id · 20261006]` (модель копирует шапку — R-2);
 * голые скобки без `#` не считаются — их чистит клиент. Id импортированных
 * заметок сам с точкой («1720194283.716586»), поэтому имя — до пробела/скобки.
 */
export const ANSWER_REF_RE = /\[#([^\]\s]{1,120}?)(?:\s*·[^\]]*)?\]/g;
const ANSWER_REF_ONCE_RE = /\[#[^\]\s]{1,120}(?:\s*·[^\]]*)?\]/;

/**
 * Формы, которыми ответ указывает на записи без ссылки. Список короткий, как
 * CONSENT_WORDS: это дословные обороты пересказа. «Похоже, утром было тяжело» —
 * не указание на источник и сюда не входит.
 */
const NOTES_CLAIM_RE = new RegExp(
  '(?:в (?:мо[еи]х |тво[еи]х |этих |найденных )?(?:запис[ия]х|заметк[ае]|дневник[ае])'
  + '|по (?:мо[еи]м |тво[еи]м )?запис[ия]м'
  + '|ты (?:писал|писала|пишешь|упоминал|упоминала|говорил|говорила|отмечал|отмечала|рассказывал|рассказывала)'
  + '|в (?:тот|этот) (?:же|самый) день)',
);

export function hasResultsDelivery(materials: string | null | undefined): boolean {
  const doc = materials ?? '';
  return RESULTS_HEAD_RE.test(doc) && RESULTS_FOUND_RE.test(doc);
}

export function notesClaimWithoutRef(answer: string, materials: string | null | undefined): boolean {
  if (!answer.trim()) return false;

  if (!hasResultsDelivery(materials)) return false;
  if (ANSWER_REF_ONCE_RE.test(answer)) return false;
  return NOTES_CLAIM_RE.test(fold(answer));
}
