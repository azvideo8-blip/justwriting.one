/**
 * Системные промпты служебных вызовов `callType: 'system_task'`.
 *
 * EA-1: служебный вызов идёт мимо дневного лимита чата (отдельный пул) и с
 * бюджетом 2048 токенов, а системный промпт для него раньше присылал клиент —
 * то есть любой вошедший получал модель общего назначения со своим промптом.
 * Теперь сервер принимает для `system_task` только промпт из этого списка
 * (точное совпадение), а остальным служебным вызовам свой промпт запрещён.
 * Клиент берёт текст отсюда же, поэтому списки не разъедутся.
 */

const PROFILE_ABSTRACTION_RULE = ' Описывай устойчивые черты характера, склонности и способы думать и чувствовать — а не конкретные события и обстоятельства. Субъект описания — сам пользователь: слова, чувства, вещи и страхи других людей из его заметок (клиентов, партнёров, родственников) не являются его чертами; о таком говори только как о другом человеке и не приписывай пользователю. Не называй имена людей, места, даты, работодателей, диагнозы и прочую конкретику из заметок; встретив такую деталь во входных данных, обобщай её до свойства характера, которое за ней стоит (например, вместо «тяжело переживает развод с Иреной в 2019 году» — «тяжело переживает завершение значимых отношений»).';

const profilePrompt = (task: string): string =>
  `Ты — профессиональный психоаналитик. На основе тем профиля пользователя ${task}${PROFILE_ABSTRACTION_RULE} НЕ рассуждай вслух — сразу результат в Markdown.`;

export const SYSTEM_TASK_PROMPTS = {
  dialogueSummary: 'Составь 1-2 предложения: о чём был этот диалог и к какому выводу пришли. Только факты, без оценок.',
  profileThemes: profilePrompt('опиши его главные темы и интересы (3-5 предложений, без заголовков и списков) — как области жизни и характер вовлечённости в них (любопытство, чувство долга, избегание), а не конкретные проекты или обстоятельства.'),
  profileEmotionalPatterns: profilePrompt('опиши его эмоциональные тенденции и паттерны мышления (3-5 предложений, без заголовков и списков).'),
  profileStrengths: profilePrompt('опиши его психологические сильные стороны (3-5 предложений, без заголовков и списков).'),
  profileGrowth: profilePrompt('опиши его зоны роста и направления развития (3-5 предложений, без заголовков и списков).'),
  profileCommunication: `Ты — профессиональный психоаналитик. На основе тем профиля пользователя, метрик стиля письма и предпочтений в общении с ИИ составь описание его стиля общения и предпочтений в коммуникации (3-5 предложений, без заголовков и списков).${PROFILE_ABSTRACTION_RULE} НЕ рассуждай вслух — сразу результат в Markdown.`,
} as const;

const ALLOWED = new Set<string>(Object.values(SYSTEM_TASK_PROMPTS));

export function isAllowedSystemTaskPrompt(prompt: string | null | undefined): boolean {
  return typeof prompt === 'string' && ALLOWED.has(prompt);
}
