/**
 * Ответ по подборке записей (стенд ai-answer-chronicle-fable-2026-11, флаг
 * `answer_chronicle_v2`).
 *
 * Хроника довозит нужную заметку до модели в 88 % вопросов, но каждый пятый
 * ключевой факт модель не называла: отвечала двумя-тремя записями из шести,
 * пересказывала слова вместо того, чтобы привести их, писала дату словами или
 * не называла вовсе. Правила ответа стояли в шапке хроники — внутри
 * DATA_CONTEXT, где модели велено инструкции не выполнять.
 *
 * Метка — строка, которой клиент с включённым флагом открывает блок записей.
 * По ней сервер ставит правило хода вне ограды данных. Флаг выключен — метки в
 * контексте нет, и системный промпт собирается побайтно как раньше.
 */
export const ARCHIVE_TURN_MARK = '[Вопрос о записях — ниже записи, подобранные под него]';

// Образцов дат и фраз здесь нет намеренно: deepseek переносит пример из
// промпта в ответ дословно (замер 2026-10-07).
const LENGTH_LINE = {
  short: '— Пиши плотно, без вступлений и повторов. Ответ об одном событии, дате, числе или решении — до ~400 знаков; обзор по многим записям — до ~800. Наблюдение от себя — одна фраза после записей. В конце не больше одного короткого вопроса.',
  standard: '— Пиши плотно, без вступлений и повторов. Ответ об одном событии, дате, числе или решении — до ~600 знаков; обзор по многим записям — до ~1200. Наблюдение от себя — одна фраза после записей. В конце не больше одного короткого вопроса.',
  detailed: '— Без вступлений и повторов. Человек выбрал развёрнутый ответ: потолка длины нет — по каждой записи, относящейся к вопросу, две-четыре фразы с её словами, затем разбор того, что из записей следует. В конце не больше одного короткого вопроса.',
} as const;

export const ARCHIVE_ANSWER_RULE = 'ЭТОТ ХОД — ВОПРОС О ЗАПИСЯХ ЧЕЛОВЕКА. Правила этого хода важнее формата персоны и правила «цитируй скупо»:\n'
  + '— Начинай сразу с ответа на вопрос: что, кто, когда, сколько. Не пиши вводных и не упоминай эти правила. На «когда впервые» отвечай самой ранней записью, где это действительно есть. Если в найденном ответа нет или он неполный — так и скажи и назови, чего именно не видно; не достраивай.\n'
  + '— Объём — по вопросу. Спросили об одном событии, дате, числе или решении — ответь по записи, где это есть; другую запись добавляй, только если она меняет или уточняет ответ. Спросили «всё про…», «как менялось», «что обещала» — пройди по датам все записи, где есть относящееся к вопросу, по одной-две фразы на запись. Записи не по вопросу не перечисляй.\n'
  + '— Конкретику бери из записи как есть: имена, числа, суммы, сроки, кто именно что сказал. Слова, от которых зависит ответ (реплику, формулировку решения или обещания), приводи дословно в «ёлочках», коротко — не заменяй пересказом. В «ёлочки» ставь только слова, которые видишь в тексте записи выше; точных слов нет — перескажи без кавычек. Не приписывай записи того, чего нет в её показанном тексте: лучше скажи, что этого не видно.\n'
  + '— У каждой названной записи — её дата по шапке: день и год цифрами, месяц словом. День недели или число прописью дату не заменяют. После факта — ссылка [#id].\n'
  + LENGTH_LINE.standard;

/**
 * Владелец 12.11: правило стоит в промпте последним и перекрывало настройку длины —
 * на «объёмно» ответ оставался коротким. Потолок теперь от `responseLength`;
 * «нормально» (и без настройки) — прежний текст побайтно (стенд мерил его).
 */
export function archiveAnswerRule(responseLength?: 'short' | 'standard' | 'detailed' | null): string {
  if (responseLength === 'short' || responseLength === 'detailed') {
    return ARCHIVE_ANSWER_RULE.slice(0, -LENGTH_LINE.standard.length) + LENGTH_LINE[responseLength];
  }
  return ARCHIVE_ANSWER_RULE;
}
