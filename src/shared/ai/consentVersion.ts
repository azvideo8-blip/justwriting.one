/**
 * Версия текста политики и согласий — одно число на клиента и сервер.
 *
 * Живёт в src/shared, а не в src/core, потому что его читает и api-слой
 * (api/postgresAiContext.ts): сервер сверяет колонку `ai_consent_version`, и
 * собственное число там означает расхождение. Так и вышло: сервер требовал 2,
 * клиент при 2 показывал в Настройках «Согласие не предоставлено», хотя ИИ
 * человеку был доступен (D-6).
 *
 * Поднимать при изменении текста политики: значение сравнивается с
 * privacyVersion и aiConsentVersion в профиле, и большее число означает, что
 * согласие нужно собрать заново.
 */
export const PRIVACY_VERSION = 3;

/**
 * Минимальная версия согласия на ИИ. `aiConsentVersion` в профиле пишется тем же
 * PRIVACY_VERSION (PrivacyModal, AccountAISection), поэтому отдельная константа
 * здесь — это имя для смысла, а не второе число, которое может разойтись.
 */
export const AI_CONSENT_VERSION_REQUIRED = PRIVACY_VERSION;
