/**
 * К25-1 (случай #25): форма обращения — «ты» или «вы» — решается кодом, одна на
 * диалог. Правило промпта («на «ты», если человек сам не пишет на «вы»») и
 * раздел портрета «Стиль общения» шли в ход оба, и модель выбирала между ними
 * по-разному от хода к ходу: ходы 1–3 на «вы», 4 вперемешку, 6 на «ты».
 *
 * Порядок: как человек сам обращается к собеседнику в своих репликах; не
 * видно — что сказано об обращении в портрете; иначе «ты».
 */
export type AddressForm = 'ty' | 'vy';

const B = '(?:^|[^а-яё])';
const E = '(?![а-яё])';
// Обращение к собеседнику: «вы/вас/вам/ваш…» и повелительное на «-ите». В рассказе
// «вы» бывает и о других («вы же знаете, как у нас»), поэтому решает перевес, а не одно слово.
const VY_RE = new RegExp(`${B}(?:вы|вас|вам|вами|ваш[а-яё]*|скажите|подскажите|объясните|помогите|посмотрите|разберите|напишите|ответьте)${E}`, 'gi');
const TY_RE = new RegExp(`${B}(?:ты|тебя|тебе|тобой|твой|твоя|тво[её]|твои[а-яё]*|скажи|подскажи|объясни|помоги|посмотри|разбери|напиши|ответь)${E}`, 'gi');
// Цитата чужой речи в реплике («она сказала: «ты всегда…»») — не обращение к собеседнику.
const QUOTED_RE = /«[^»]*»|"[^"]*"|„[^“]*“/g;

const PORTRAIT_VY_RE = /на\s*«?вы»?|обращ[а-яё]*\s+на\s*«?вы|предпочитает\s+«?вы/i;
const PORTRAIT_TY_RE = /на\s*«?ты»?|обращ[а-яё]*\s+на\s*«?ты|предпочитает\s+«?ты/i;

interface Msg { role: string; content: string }

export function addressFormOf(messages: readonly Msg[] | null | undefined, portrait: string | null | undefined): AddressForm {
  let vy = 0;
  let ty = 0;
  for (const m of messages ?? []) {
    if (m.role !== 'user') continue;
    const own = m.content.toLowerCase().replace(QUOTED_RE, ' ');
    vy += own.match(VY_RE)?.length ?? 0;
    ty += own.match(TY_RE)?.length ?? 0;
  }
  if (vy > ty) return 'vy';
  if (ty > vy) return 'ty';
  if (portrait) {
    const vyP = PORTRAIT_VY_RE.test(portrait);
    const tyP = PORTRAIT_TY_RE.test(portrait);
    if (vyP && !tyP) return 'vy';
  }
  return 'ty';
}

