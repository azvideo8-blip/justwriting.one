/** Метка блока: по ней сервер ставит правило хода вне ограды данных (как HYPOTHESIS_TURN_MARK). */
export const INSIGHT_RECALL_MARK = '[Вывод из прошлого разговора — человек с ним тогда согласился]';

const ruDate = (iso: string) => { const [y, m, d] = iso.split('-'); return `${d}.${m}.${y}`; };

/** Блок для ограды данных: дата кодом, вывод — в «ёлочках» как чужая речь. */
export function insightRecallBlock(insight: { date: string; text: string }): string {
  return `${INSIGHT_RECALL_MARK}\n— ${ruDate(insight.date)}: «${insight.text.replace(/[«»]/g, '"')}»`;
}

