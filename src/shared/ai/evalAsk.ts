/**
 * ED-2 (0.10.8): ход-оценка у Редактора. Человек просит оценку черновика
 * («как тебе», «оцени», «что не так»), а получает переписанный пост: ANSWER
 * FORMAT требует начинать ответ с первой строки поста, «ОТВЕТ НА ХОД» — сначала
 * ответить на сказанное. Как и `turnScope` — словарь маркеров, не классификатор;
 * промах безопасен, ANSWER FORMAT остаётся в промпте.
 *
 * Просьба написать или переписать сильнее просьбы об оценке: «оцени и перепиши»
 * — это новая версия поста, режим оценки не включается.
 */
const EVAL_ASK_RE = /(?:^|[^а-яёА-ЯЁ])(?:как тебе|оцени|оцените|дай оценку|какая оценка|что думаешь|что скажешь|что добавить|что бы ты добавил|что бы добавить|чего не хватает|что не так|что улучшить|как улучшить)/i;
// ED-2b: любая просьба изменить текст — повелительный глагол правки — сильнее
// оценки: «оцени и сократи», «исправь что не так», «сделай как тебе нравится».
// «Напиши» — правка только с объектом-постом: «напиши, чего не хватает» — оценка.
const EDIT_VERB_RE = /(?:^|[^а-яё])(?:перепиши|переделай|сделай|собери|составь|сократи|исправь|поправь|допиши|добавь|дополни|убери|измени|улучши|расширь)(?:те)?(?![а-яё])/i;
const REWRITE_ASK_RE = /перепиш|(?:^|[^а-яёА-ЯЁ])напиши(?:\s+\S+){0,2}\s+(?:пост|версию|черновик)|нов(?:ую|ая)\s+верси/i;

/** `question` — только вопрос человека, без строки вложения: название заметки
 *  («Что не так с этой осенью») не должно включать режим оценки (ED-2c). */
export function evalAskMode(question: string): boolean {
  return EVAL_ASK_RE.test(question) && !EDIT_VERB_RE.test(question) && !REWRITE_ASK_RE.test(question);
}
