/**
 * Собеседник «Транзактный аналитик» (`ta`, флаг `chat_persona_ta`): шаг хода.
 *
 * Модель копирует примеры из промпта дословно (стенд A/B 07.10), поэтому
 * готовых фраз здесь нет — строка хода говорит смысл шага, слова модель
 * подбирает сама. Шаг считает код по истории разговора, а не модель:
 *   - `parent`: в реплике слышно давление («должен», «надо», «нельзя»…), а в
 *     двух последних ответах о Родителе не говорили — иначе на каждом «надо»
 *     один и тот же ход надоест;
 *   - `adult`: прошлый ответ назвал Родителя, а Взрослого ещё не звал —
 *     человек ответил, теперь очередь Взрослого.
 * Иначе строки нет, и собеседник идёт по общей инструкции.
 */

export type TaStep = 'parent' | 'adult';

const B = '(?:^|[^а-яё])';
const E = '(?![а-яё])';
// «Нужно» сознательно не берём: «нужно купить хлеб» — дело, а не голос Родителя.
// 27.3 (владелец 19.11: ТА держит язык состояний и после гипотез): давление звучит
// и как запрет себе — «позволить/разрешить себе», «не заслужил(а)», «имею ли
// право», страх нехватки — «вдруг не хватит», «жалко тратить». Очерёдность
// («в первую очередь…») не берём: чаще это дела, а не голос Родителя.
const PRESSURE_RE = new RegExp(`${B}(?:должн[аоы]?|долж[её]н|надо|обязан[аоы]?|приходится|прид[её]тся|нельзя|не имею права|не имела права|не имел права|положено|так правильно|так принято|стыдно не|позвол(?:ить|яю|ила?|ю) себе|разреш(?:ить|аю|ила?|у) себе|не заслужил[аи]?|не заслуживаю|имею ли (?:я )?право|вдруг не хватит|жалко (?:тратить|денег)|стыдно тратить)${E}`, 'i');
const PARENT_RE = /Родител/;
const ADULT_RE = /Взросл/;

interface Msg { role: string; content: string }

export function taStepOf(messages: readonly Msg[] | null | undefined): TaStep | null {
  if (!messages || messages.length === 0) return null;
  if (messages[messages.length - 1]?.role !== 'user') return null;
  // История проходится по порядку: шаг Взрослого — только сразу после шага
  // Родителя и один раз. Модель не всегда зовёт Взрослого, когда её просят
  // (стенд 18.11: три хода подряд «очередь Взрослого»), и без этого шаг
  // крутился бы, пока она не скажет нужное слово.
  const replies: string[] = [];
  let step: TaStep | null = null;
  for (const m of messages) {
    if (m.role === 'assistant') { replies.push(m.content); continue; }
    if (m.role !== 'user') continue;
    const prev = replies[replies.length - 1] ?? '';
    // Прошлый ответ — шаг Родителя: назвал Родителя, Взрослого ещё не звал. Слово
    // «Ребёнок» модель пишет не всегда («та часть тебя, что устала» — стенд 18.11,
    // 2 из 3), поэтому его не требуем.
    if (step === 'parent' && PARENT_RE.test(prev) && !ADULT_RE.test(prev)) step = 'adult';
    else if (PRESSURE_RE.test(m.content.toLowerCase()) && !replies.slice(-2).some(r => PARENT_RE.test(r))) step = 'parent';
    else step = null;
  }
  return step;
}

