// Удаление заметки сносит портрет (он мог опираться на неё). Проход генерации,
// начатый ДО удаления, дописывал портрет обратно — и разбор удалённой заметки
// возвращался и в облако (R3-009). Проход запоминает эпоху на старте и не
// сохраняет результат, если она сменилась.
// ponytail: счётчик одной вкладки; другая вкладка узнает об удалении только
// со следующим проходом. Межвкладочно — BroadcastChannel, если понадобится.
let epoch = 0;

export function invalidatePortrait(): void {
  epoch += 1;
}

export function getPortraitEpoch(): number {
  return epoch;
}
