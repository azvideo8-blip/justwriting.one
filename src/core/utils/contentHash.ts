/**
 * Короткая метка содержимого для служб синхронизации: SF2-1 (спор черновика) и
 * SF2-2 (спор скалярного ИИ-стора) различают «это наша же версия» по хэшу, а не
 * по тексту — хранить сам текст второй копией нельзя, локальные строки и так
 * упираются в потолок 500 КБ.
 *
 * FNV-1a в двух инициаторах: синхронная, стабильна между сборками (crypto.subtle
 * асинхронна и не живёт в сравнении копий), 16 шестнадцатеричных знаков.
 * Столкновение означает обычный спор копий, а не потерю данных: оно либо отдаёт
 * облако локальной копии, либо оставляет локальное — обе ветки видны человеком.
 */
export function contentHash(s: string): string {
  let a = 0x811c9dc5;
  let b = 0xcbf29ce4;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    a = Math.imul(a ^ c, 0x01000193);
    b = Math.imul(b ^ (c + 0x9e3779b9), 0x01000193);
  }
  return `${(a >>> 0).toString(16).padStart(8, '0')}${(b >>> 0).toString(16).padStart(8, '0')}`;
}
