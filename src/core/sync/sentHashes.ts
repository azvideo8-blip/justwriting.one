/**
 * Список хэшей нагрузок, которые УЕХАЛИ в облако и ответа не увидели.
 *
 * Нужен именно списком, а не одним полем, по одной причине: облако обязано
 * узнавать СВОЮ же версию, когда ответ на запись потерялся уже после коммита на
 * сервере. На плохой сети подряд падает несколько сохранений, и между двумя
 * загрузками страницы в облаке может лежать ЛЮБОЕ из уехавших состояний — по
 * одному хэшу мы бы его не нашли, приняли бы свою запись за чужую правку и
 * отдали облаку спор копий (SF3-1 — затёртый набор; SF3-3 — вечный конфликт
 * скалярного ИИ-стора).
 *
 * Предельное число — 64: облако черновика пишется не чаще раза в 30 с, значит
 * это полчаса непрерывной плохой сети. Дальше список начинает вытеснять самое
 * старое доказательство, и правоту держит локальная копия, а не хэши.
 *
 * Форма одна для двух потребителей (спор черновика и спор скаляра): 16-значный
 * `contentHash` на запись, старшие в начале.
 */
export const SENT_HASH_CAP = 64;

/** Добавить хэш отправки: уже в списке — без изменений, иначе в конец с подрезкой потолка. */
export function pushSentHash(hashes: string[], hash: string, cap = SENT_HASH_CAP): string[] {
  if (hashes.includes(hash)) return hashes;
  return [...hashes, hash].slice(-cap);
}

/** Прочитать список из служебного поля строки: не список или мусор — пустой список («не помним»). */
export function readSentHashes(value: unknown): string[] {
  return Array.isArray(value) ? value.filter((h): h is string => typeof h === 'string') : [];
}
